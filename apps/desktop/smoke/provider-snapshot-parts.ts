/**
 * ⚑ **One section of Claude Code's context message, as its transcript keeps it**: the attachment's
 * own type (`skill_listing`, `agent_listing_delta`…) and the text it rendered into the message.
 */
export interface ClaudeContextSection {
  readonly label: string
  readonly text: string
}

/**
 * ⚑ **A section as a context message carries it.** The transcript keeps each section Claude Code
 * rendered in the system's role wrapped in `<system-reminder>`; on a model that takes a
 * mid-conversation system message (`mid_conv_system` in Claude Code's catalogue) the context message
 * carries it unwrapped, the sections joined by a blank line — measured on Claude Code 2.1.287's own
 * requests, where they rebuild the message character for character. ⚠️ A model without it (Haiku)
 * gets them wrapped, as reminders in the first message, and has no context message to cut.
 */
function asTheContextMessageCarriesIt(rendered: string): string {
  const unwrapped = /^<system-reminder>\n([\s\S]*)\n<\/system-reminder>$/.exec(rendered)
  return unwrapped?.[1] ?? rendered
}

/**
 * 🔴 **W4.186 · the context message's sections, from Claude Code's own transcript**: each
 * `attachment` it rendered in the system's role (`renderedRole`) after the first message with
 * `marker`, in order, up to the model's answer — the text each became (`rendered`), as the context
 * message carries it ({@link asTheContextMessageCarriesIt}).
 */
export function claudeContextSections(transcript: string, marker: string): ClaudeContextSection[] {
  const sections: ClaudeContextSection[] = []
  let after = false
  for (const line of transcript.split('\n')) {
    if (line.trim() === '') continue
    const record = JSON.parse(line) as Record<string, unknown>
    if (!after) {
      after = record['type'] === 'user' && line.includes(marker)
      continue
    }
    if (record['type'] === 'assistant') break
    if (record['type'] !== 'attachment' || record['renderedRole'] !== 'system') continue
    const rendered = Array.isArray(record['rendered']) ? (record['rendered'] as unknown[]) : []
    const attachment = (record['attachment'] ?? {}) as Record<string, unknown>
    const text = rendered
      .flatMap((one) =>
        blocksOf((one as { content?: unknown } | null)?.content).map((block) => block.text ?? ''),
      )
      .join('\n\n')
    if (text !== '') {
      sections.push({
        label: String(attachment['type'] ?? 'attachment'),
        text: asTheContextMessageCarriesIt(text),
      })
    }
  }
  return sections
}

/** The text of every block in a request's messages, tool results' included. */
function everyText(request: unknown): string[] {
  const out: string[] = []
  const walk = (value: unknown): void => {
    if (typeof value === 'string') return
    if (Array.isArray(value)) {
      for (const one of value) walk(one)
      return
    }
    if (typeof value !== 'object' || value === null) return
    const record = value as Record<string, unknown>
    if (typeof record['text'] === 'string') out.push(record['text'])
    if (typeof record['content'] === 'string') out.push(record['content'])
    for (const [key, inner] of Object.entries(record)) if (key !== 'text') walk(inner)
  }
  walk((request as ClaudeRequest).messages ?? [])
  return out
}

/** The names of Claude Code's own deferred tools, as its deferred list gives them to the model. */
export function claudeDeferredBuiltIns(request: unknown): string[] {
  for (const text of everyText(request)) {
    const at = text.indexOf('deferred tools are now available via ToolSearch')
    if (at === -1) continue
    const list =
      text.slice(text.indexOf('\n', at) + 1).split(/\n\s*\n|\n<\/system-reminder>/)[0] ?? ''
    return list
      .split('\n')
      .map((line) => line.trim())
      .filter((name) => /^\w+$/.test(name) && !name.startsWith('mcp__'))
  }
  return []
}

/**
 * 🔴 **Claude Code's deferred tools, in full**: once its ToolSearch has answered with their names
 * (`tool_reference`), the next request carries each in its tools, marked `defer_loading` — read
 * from that request.
 */
export function claudeLoadedTools(
  request: unknown,
  names: readonly string[],
  scrubs: readonly Scrub[],
): SnapshotPart | null {
  const offered = (request as ClaudeRequest).tools ?? []
  const tools = names.flatMap((name) => {
    const declared = offered.find((tool) => tool.name === name)
    return declared === undefined ? [] : [{ name, text: scrubbed(asSent(declared), scrubs) }]
  })
  if (tools.length === 0) return null
  return withWhatVaries(
    part(
      'claude.tools.deferred',
      'Its deferred built-in tools, in full, as they are sent once the model asks for them by name',
      'tools',
      'when-loaded',
      tools.map((one) => one.text).join('\n'),
      tools,
    ),
  )
}

/**
 * The model's name and id as Claude Code tells it to the model — read from the request, so the
 * placeholders replace exactly what was sent.
 */
export function claudeModelNamed(request: unknown): { name: string; id: string } | null {
  const text = JSON.stringify(request)
  const said = /You are powered by the model named (.+?)\. The exact model ID is (\S+?)\./.exec(
    text,
  )
  return said === null ? null : { name: said[1] ?? '', id: said[2] ?? '' }
}

/**
 * 🔴 **Claude Code's own parts of its first request.**
 *  - the system prompt, with BroBot's appended text (`append`, exactly as BroBot sent it) made a
 *    placeholder where it joined;
 *  - its tools, without the servers' (`mcp__…`, BroBot's and a person's — deferred here anyway);
 *  - its reminders at the head of the first message, the memory index's own lines made a
 *    placeholder;
 *  - its context message, with the names of BroBot's tools and BroBot's paragraph made placeholders.
 */
export function claudeParts(
  request: unknown,
  brobot: { readonly append: string },
  scrubs: readonly Scrub[],
  /** The context message's sections, from Claude Code's transcript ({@link claudeContextSections}). */
  sections: readonly ClaudeContextSection[],
): SnapshotPart[] {
  const body = request as ClaudeRequest
  const parts: SnapshotPart[] = []
  const system = (body.system ?? []).map((block) => block.text ?? '')
  const [header, identity, ...rest] = system
  if (header !== undefined) {
    parts.push(
      part(
        'claude.request-header',
        'The request’s first line: Claude Code’s version, as a system block',
        'system-prompt',
        'every-request',
        scrubbed(header, scrubs),
      ),
    )
  }
  if (identity !== undefined) {
    parts.push(
      part(
        'claude.identity',
        '“You are Claude Code…”',
        'system-prompt',
        'every-request',
        scrubbed(identity, scrubs),
      ),
    )
  }
  const guidance = rest.join('\n\n')
  const at = brobot.append === '' ? -1 : guidance.indexOf(brobot.append)
  if (at === -1) throw new Error('BroBot’s appended text is not in the system prompt as sent')
  const own =
    `${guidance.slice(0, at)}${PLACEHOLDER.brobotSystemPromptText}${guidance.slice(at + brobot.append.length)}`.trim()
  parts.push(
    part(
      'claude.prompt',
      'Claude Code’s guidance: harness, session, memory, environment, context management',
      'system-prompt',
      'every-request',
      scrubbed(own, scrubs),
    ),
  )

  // ⚑ **W4.186 · the tools the model is shown**: a tool sent `defer_loading` is not — the API keeps
  // it from the model until it is asked for by name — so Claude Code's reserved one
  // (`DeferredToolPlaceholder`, *"never call this tool"*) is not the model's (the file's notes say
  // so), and a server's are BroBot's or a person's.
  const tools = (body.tools ?? []).filter(
    (tool) => !(tool.name ?? '').startsWith('mcp__') && tool.defer_loading !== true,
  )
  const declared = tools.map((tool) => ({ name: tool.name ?? '', text: asSent(tool) }))
  parts.push(
    part(
      'claude.tools',
      'Claude Code’s built-in tools sent in full; its deferred ones go by name until loaded',
      'tools',
      'every-request',
      scrubbed(declared.map((one) => one.text).join('\n'), scrubs),
      declared.map((one) => ({ name: one.name, text: scrubbed(one.text, scrubs) })),
    ),
  )

  const messages = body.messages ?? []
  const first = messages.find((message) => message.role === 'user')
  // ⚑ Its reminders at the head of the first message — on some models, its whole context too.
  for (const block of blocksOf(first?.content)) {
    const text = block.text ?? ''
    if (!text.startsWith('<system-reminder>')) continue
    const { id, title } = claudeReminderTitle(text)
    const own =
      id === 'claude.reminder.memory'
        ? text.replace(
            /(Contents of [^\n]*MEMORY\.md[^\n]*:\n\n)[\s\S]*?(\n?<\/system-reminder>)/,
            `$1${PLACEHOLDER.memoryIndex}$2`,
          )
        : withoutBroBotIn(text)
    parts.push(part(id, title, 'first-message', 'first-message', scrubbed(own, scrubs)))
  }

  const context = messages.find((message) => message.role === 'system')
  const contextText = blocksOf(context?.content)
    .map((block) => block.text ?? '')
    .join('\n\n')
  // 🔴 **W4.186 · its context message, section by section** — the skills list and the sub-agent
  // types among them, each its own part — cut where Claude Code's transcript says each began.
  // ⛔ **Every character of the message is in exactly one section**, or nothing is written: a
  // section the transcript does not name would otherwise be shown as part of another. ⚑ A model
  // with no context message (Haiku) was sent its sections as reminders, cut above.
  // ⚑ The sections, joined by a blank line and by nothing else, are the message.
  let from = 0
  for (const section of contextText === '' ? [] : sections) {
    const between = from === 0 ? '' : '\n\n'
    if (!contextText.startsWith(`${between}${section.text}`, from)) {
      throw new Error(
        `NOT PERFORMED — Claude Code’s context message does not hold its ${section.label} section where its transcript puts it`,
      )
    }
    from += between.length + section.text.length
    const known = CLAUDE_SECTIONS[section.label]
    parts.push(
      part(
        `claude.context.${known?.id ?? section.label}`,
        known?.title ?? `Another of its context sections: ${section.label}`,
        'context-message',
        'first-message',
        scrubbed(withoutBroBotIn(section.text), scrubs),
      ),
    )
  }
  if (from !== contextText.length) {
    throw new Error(
      'NOT PERFORMED — Claude Code’s context message holds text its transcript names no section for',
    )
  }
  // ⛔ One part per id: a window lists them by it.
  const ids = parts.map((one) => one.id)
  const twice = ids.find((id, at) => ids.indexOf(id) !== at)
  if (twice !== undefined) throw new Error(`NOT PERFORMED — two parts would be named ${twice}`)
  return parts.map(withWhatVaries)
}

