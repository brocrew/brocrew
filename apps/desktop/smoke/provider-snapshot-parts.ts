/** `text` with every scrub applied, longest first, and each tokens-left count made a placeholder. */
export function scrubbed(text: string, scrubs: readonly Scrub[]): string {
  let out = text
  const literals = scrubs.filter(
    (one): one is { from: string; to: string } => typeof one.from === 'string',
  )
  for (const { from, to } of literals.sort((a, b) => b.from.length - a.from.length)) {
    if (from !== '') out = out.split(from).join(to)
  }
  for (const { from, to } of scrubs) {
    if (from instanceof RegExp) out = out.replace(new RegExp(from.source, 'g'), to)
  }
  return out.replace(
    /<total_tokens>\d+ tokens left<\/total_tokens>/g,
    `<total_tokens>${PLACEHOLDER.tokensLeft} tokens left</total_tokens>`,
  )
}

/**
 * ⛔ **What must never be in a snapshot**: a path into this computer's folders, a word of BroBot's
 * own text, or a value only this capture had (`extra`: its scratch root's name, its markers).
 */
export function residueIn(text: string, extra: readonly string[] = []): string[] {
  const found: string[] = []
  const forbidden: readonly (string | RegExp)[] = [
    '/var/folders/',
    '/Users/',
    '/home/',
    'C:\\Users',
    'Composed by BroBot',
    'Composed by BroCrew',
    'Sent by a person',
    'brobot2:profile-instructions',
    'mcp__brobot__',
    'brobot__',
    'reach the app you are running inside',
    'BROBOT-WORKSPACE-CANARY',
    'Generated by BroBot',
    'Generated by BroCrew',
    'probe-only',
    ...extra,
  ]
  for (const one of forbidden) {
    if (typeof one === 'string' ? text.includes(one) : one.test(text)) found.push(String(one))
  }
  return found
}

/** A part, measured by the shared rule — sizes are computed again when a snapshot is read. */
function part(
  id: string,
  title: string,
  where: SnapshotPlace,
  when: SnapshotPart['when'],
  text: string,
  tools?: readonly { name: string; text: string }[],
): SnapshotPart {
  return {
    id,
    title,
    where,
    when,
    text,
    chars: 0,
    words: 0,
    approxTokens: 0,
    ...(tools === undefined ? {} : { tools: tools.map((one) => ({ ...one, chars: 0 })) }),
  }
}

