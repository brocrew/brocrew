/** The texts of `parts` moved into `texts` by their hash; the parts keep the hashes. */
export function keep(parts: readonly SnapshotPart[], texts: Record<string, string>): KeptPart[] {
  const ref = (text: string): string => {
    const hash = createHash('sha256').update(text).digest('hex').slice(0, 16)
    texts[hash] = text
    return hash
  }
  return parts.map((one) => ({
    id: one.id,
    title: one.title,
    where: one.where,
    when: one.when,
    text: one.tools === undefined ? ref(one.text) : '',
    ...(one.tools === undefined
      ? {}
      : { tools: one.tools.map((tool) => ({ name: tool.name, text: ref(tool.text) })) }),
    ...(one.varies === undefined ? {} : { varies: one.varies }),
  }))
}
