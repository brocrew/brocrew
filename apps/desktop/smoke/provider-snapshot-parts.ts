/** The name of a developer or user text Codex writes, from how it opens. */
function codexTextTitle(text: string): { id: string; title: string } {
  const opens: readonly [RegExp, string, string][] = [
    [/^You are Codex/, 'codex.prompt', 'Codex’s base prompt'],
    [/^## Memory\b/, 'codex.memory', 'Its memory instructions, around the agent’s memory summary'],
    [/^<skills_instructions>/, 'codex.skills', 'Its skills list'],
    [/^<permissions instructions>/, 'codex.permissions', 'Its sandbox and approval rules'],
    [/^<collaboration_mode>/, 'codex.collaboration-mode', 'Its collaboration mode'],
    [/^(?:<multi_agent_role>|You are `\/root`)/, 'codex.multi-agent-role', 'Its multi-agent role'],
    [/^<multi_agent_mode>/, 'codex.multi-agent-mode', 'Its multi-agent mode'],
    [/^<environment_context>/, 'codex.environment', 'Its environment context'],
    [
      /^# AGENTS\.md instructions for /,
      'codex.agents-wrapper',
      'Its wrapper around the AGENTS files',
    ],
  ]
  for (const [pattern, id, title] of opens) if (pattern.test(text)) return { id, title }
  return { id: 'codex.other', title: 'Another of its own messages' }
}

/** Codex's tools, without BroBot's: its `brobot` namespace, or BroBot's section of `exec`. */
function codexTools(tools: readonly CodexTool[]): { name: string; text: string }[] {
  const out: { name: string; text: string }[] = []
  for (const tool of tools) {
    if (tool.name === 'brobot') continue
    if (tool.type === 'namespace') {
      // ⚑ The namespace's own words, which the model sees too.
      out.push({ name: tool.name ?? '', text: asSent({ ...tool, tools: undefined }) })
      for (const inner of tool.tools ?? []) {
        const own =
          inner.name === 'exec' && typeof inner.description === 'string'
            ? {
                ...inner,
                description: inner.description.replace(
                  /^## brobot\n[\s\S]*?(?=\n## |(?![\s\S]))/m,
                  `## brobot\n${PLACEHOLDER.brobotToolDeclarations}\n`,
                ),
              }
            : inner
        out.push({ name: `${tool.name ?? ''}.${inner.name ?? ''}`, text: asSent(own) })
      }
      continue
    }
    out.push({ name: tool.name ?? tool.type ?? '', text: asSent(tool) })
  }
  return out
}

/**
 * 🔴 **Codex's own parts of its first request**, in either of its two shapes:
 *  - `functions`: its prompt as the request's instructions, its tools as the request's tools;
 *  - `exec`: its tools in an `additional_tools` item, each declared as code inside `exec`, and its
 *    prompt as the first developer message.
 * ⚑ Cut out: BroBot's tools, the AGENTS files BroBot wrote (Codex's wrapper around them stays), and
 * BroBot's own user message. The memory summary is the agent's: a placeholder.
 */
export function codexParts(
  request: unknown,
  scrubs: readonly Scrub[],
  /** BroBot's own user message: its first-turn lead and the words, which are not Codex's. */
  isBroBots: (text: string) => boolean,
): { shape: 'functions' | 'exec'; parts: SnapshotPart[] } {
  const body = request as CodexRequest
  const input = body.input ?? []
  const additional = input.find((item) => item.type === 'additional_tools')
  const shape = additional === undefined ? 'functions' : 'exec'
  const parts: SnapshotPart[] = []
  if (typeof body.instructions === 'string' && body.instructions !== '') {
    parts.push(
      part(
        'codex.prompt',
        'Codex’s base prompt',
        'instructions',
        'every-request',
        scrubbed(body.instructions, scrubs),
      ),
    )
  }
  const declared = codexTools(additional?.tools ?? body.tools ?? [])
  parts.push(
    part(
      'codex.tools',
      shape === 'exec'
        ? 'Its tools: one `exec` tool declaring each as code, and the tools beside it'
        : 'Its built-in tools',
      'tools',
      // ⚑ Code mode's tools ride in an input item, at the head of the conversation.
      shape === 'exec' ? 'first-message' : 'every-request',
      scrubbed(declared.map((one) => one.text).join('\n'), scrubs),
      declared.map((one) => ({ name: one.name, text: scrubbed(one.text, scrubs) })),
    ),
  )
  for (const item of input) {
    if (item.type !== 'message' || (item.role !== 'developer' && item.role !== 'user')) continue
    for (const block of item.content ?? []) {
      const text = block.text ?? ''
      // ⚑ BroBot's own user message — its lead and the words — is BroBot's, not Codex's.
      if (item.role === 'user' && isBroBots(text)) continue
      const { id, title } = codexTextTitle(text)
      let own = text
      if (id === 'codex.memory') {
        own = own.replace(
          /(=+ MEMORY_SUMMARY BEGINS =+\n)[\s\S]*?(\n=+ MEMORY_SUMMARY ENDS =+)/,
          `$1${PLACEHOLDER.memorySummary}$2`,
        )
      }
      if (id === 'codex.agents-wrapper') {
        // ⚑ Codex's own separator between the two files stays: it is Codex's text.
        own = own.replace(
          /(<INSTRUCTIONS>\n)([\s\S]*?)(\n<\/INSTRUCTIONS>)/,
          (_all, open, inside, close) =>
            `${String(open)}${
              String(inside).includes('\n--- project-doc ---\n')
                ? `${PLACEHOLDER.agentsFiles}\n\n--- project-doc ---\n\n${PLACEHOLDER.workspaceAgentsFile}`
                : PLACEHOLDER.agentsFiles
            }${String(close)}`,
        )
      }
      parts.push(
        part(
          id,
          title,
          item.role === 'developer' ? 'developer-message' : 'user-message',
          'first-message',
          scrubbed(own, scrubs),
        ),
      )
    }
  }
  return { shape, parts }
}

