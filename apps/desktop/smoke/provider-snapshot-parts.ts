/**
 * 🔴 **W4.164 · F093 R3 — a provider's own parts, cut out of one request it sent its model.**
 *
 * The probe (`provider-snapshots.smoke.ts`) runs BroBot's real host against a local stand-in model
 * and hands each first request here. ⚑ **What is cut out is BroBot's**, found by what BroBot itself
 * sent (its appended system text) and by the names its tools and texts carry; ⚑ **what is replaced
 * is this conversation's**, found by the probe's own scratch values, never guessed. ⛔ A snapshot
 * that still holds a scratch path, a home, or a word of BroBot's is refused ({@link residueIn}).
 */

/**
 * One value of this capture, and the placeholder that stands for it in a snapshot: a literal, or a
 * pattern for a value the capture cannot know exactly (a date written in the computer's own zone).
 */
export interface Scrub {
  readonly from: string | RegExp
  readonly to: string
}

