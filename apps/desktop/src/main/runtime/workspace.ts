const GENERATED_HEADER =
  '<!-- Generated by BroBot. Rendered from one canonical source; edits here are overwritten. -->'
const GENERATED_MARKER = `Instruction marker: ${WORKSPACE_CANARY}`
const RETIRED_FILE_MAX_BYTES = 16 * 1024

// Only files carrying both of the old ownership marks may be retired.
function retireWorkspaceInstructions(workspace: string, name: string): void {
  const path = join(workspace, name)
  const candidate = lstatOrNull(path)
  if (candidate === null || !candidate.isFile() || candidate.size > RETIRED_FILE_MAX_BYTES) return
  let fd: number
  try {
    fd = openNotThroughALink(path, constants.O_RDONLY | constants.O_NONBLOCK)
  } catch {
    return
  }
  try {
    const stat = fstatSync(fd)
    if (
      !stat.isFile() ||
      stat.size > RETIRED_FILE_MAX_BYTES ||
      stat.dev !== candidate.dev ||
      stat.ino !== candidate.ino ||
      stat.size !== candidate.size ||
      stat.mtimeMs !== candidate.mtimeMs ||
      stat.ctimeMs !== candidate.ctimeMs
    )
      return
    const bytes = Buffer.alloc(RETIRED_FILE_MAX_BYTES + 1)
    const size = readSync(fd, bytes, 0, bytes.length, 0)
    if (size !== stat.size) return
    const content = bytes.subarray(0, size).toString('utf8')
    if (!content.startsWith(`${GENERATED_HEADER}\n\n`)) return
    if (!content.trimEnd().endsWith(GENERATED_MARKER)) return
    const current = lstatSync(path)
    if (
      !current.isFile() ||
      current.dev !== stat.dev ||
      current.ino !== stat.ino ||
      current.size !== stat.size ||
      current.mtimeMs !== stat.mtimeMs ||
      current.ctimeMs !== stat.ctimeMs
    )
      return
    unlinkSync(path)
  } finally {
    closeSync(fd)
  }
}

function errno(error: unknown): string | undefined {
  return (error as NodeJS.ErrnoException | undefined)?.code
}

function lstatOrNull(path: string): Stats | null {
  try {
    return lstatSync(path)
  } catch {
    return null
  }
}

function statOrNull(path: string): Stats | null {
  try {
    return statSync(path)
  } catch {
    return null
  }
}

export function publishOwnFile(
  dir: string,
  name: string,
  content: string,

  where = 'the BroCrew workspace',
): void {
  const path = join(dir, name)
  const staged = aStagingName(join(dir, `.${name}`))
  let fd: number
  try {
    // A name nobody knows, made new: nothing planted at it can send the write somewhere else.
    fd = createFreshFile(staged)
  } catch (cause) {
    throw new Error(`could not stage ${path}: ${errno(cause) ?? String(cause)}`, { cause })
  }
  // ⛔ **Every exit from here removes the staging file it made.** A first draft closed the
  // descriptor in a `finally` and let a failed WRITE — a full disk — propagate with the empty
  // staged file still sitting in the agent's working directory, once per launch. Found reading this
  // diff back rather than by a test, because no test fills a disk.
  const discard = (cause: unknown, message: string): never => {
    try {
      unlinkSync(staged)
    } catch {
      // best effort: leaving one staging file behind is better than losing the real error
    }
    throw new Error(message, { cause })
  }
  try {
    writeFileSync(fd, content)
  } catch (cause) {
    discard(cause, `could not write ${path}: ${errno(cause) ?? String(cause)}`)
  } finally {
    try {
      closeSync(fd)
    } catch {
      // the content is already written; a failed close is not a failed publish
    }
  }
  try {
    renameSync(staged, path)
  } catch (cause) {
    discard(
      cause,
      `could not put ${name} in ${where} — something else is at ${path} ` +
        `(${errno(cause) ?? String(cause)})`,
    )
  }
}

// Create the durable folder and retire only the app's previous instruction files.
export function ensureWorkspace(userData: string): string {
  const workspace = brobotWorkspace(userData)
  // ⚠️ **`lstat` decides whether to create; it does not decide whether to trust.** The second read
  // below is the one the writes rely on, so the answer is always about a directory that exists.
  //
  // ⛔ **And the create is skipped when anything is already there, because `mkdir -p` cannot be
  // asked about it.** A first draft called `mkdirSync(…, {recursive: true})` unconditionally and
  // treated `EEXIST` as "something is in the way" — wrong on the case that matters: recursive
  // `mkdir` RESOLVES the path, so a DANGLING symlink at the workspace raises **ENOENT**, which
  // that draft rethrew as a raw `mkdir` errno instead of the sentence below. The test for it is
  // what said so.
  let at = lstatOrNull(workspace)
  if (at === null) {
    mkdirSync(workspace, { recursive: true, mode: 0o700 })
    at = lstatOrNull(workspace)
  }
  // A link or junction the person made to keep the workspace on another disk is followed: what
  // decides is the folder it leads to.
  const linked = at?.isSymbolicLink() === true
  if (linked) at = statOrNull(workspace)
  if (at === null || !at.isDirectory()) {
    throw new Error(
      `the BroCrew workspace at ${workspace} is not a directory this app can own — ` +
        `${linked ? 'it is a link to no folder' : at === null ? 'nothing is there' : 'it is not a directory'}. ` +
        `Move or remove it and BroCrew will recreate the workspace.`,
    )
  }
  for (const name of workspaceInstructionNames) {
    retireWorkspaceInstructions(workspace, name)
  }
  return workspace
}
