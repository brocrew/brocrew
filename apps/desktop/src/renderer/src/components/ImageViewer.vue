<script setup lang="ts">
import { computed } from 'vue'
import { assetUrl } from '../../../shared/asset-url'
import { pathTail } from '../../../shared/path-tail'

/**
 * One image, as large as the window will allow (067).
 *
 * The transcript entry and the panel's Assets index both open this — **one viewer, two entrances**,
 * so there is one answer to "what does opening an image do" no matter where you clicked.
 *
 * Deliberately not the document viewer. That surface is built for a document: Markdown and Raw
 * views. An image has none of those and would render as a large empty frame
 * around a picture. What it DOES borrow is the white paper ground, for the same reason the entry
 * does: generated PNGs are frequently transparent.
 *
 * The chrome — Esc, backdrop click, focus trap, focus returned — belongs to `OverlayHost`, which
 * wraps this. Nothing here re-implements any of it.
 */
const props = defineProps<{ path: string; prompt?: string }>()

const emit = defineEmits<{ close: [] }>()

const src = computed(() => assetUrl(props.path))

/** The file's own name — the last segment, and the only part worth a heading. */
const name = computed(() => pathTail(props.path))
</script>

<template>
  <div class="image-viewer" data-cy="image-viewer">
    <header class="viewer-head">
      <strong class="name" :title="path">{{ name }}</strong>
      <button
        class="icon-button"
        type="button"
        aria-label="Close"
        data-cy="close-overlay"
        @click="emit('close')"
      >
        <svg class="icon"><use href="#i-x" /></svg>
      </button>
    </header>

    <div class="stage">
      <img class="full" :src="src" :alt="prompt ?? 'an image generated by the agent'" />
    </div>

    <!-- The whole prompt, unclamped. This is the surface you opened because the caption in the
         conversation was not enough. -->
    <p v-if="prompt" class="prompt" data-cy="viewer-prompt">{{ prompt }}</p>
  </div>
</template>

