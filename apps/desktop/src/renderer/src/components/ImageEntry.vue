<script setup lang="ts">
import { computed, ref } from 'vue'
import { assetUrl } from '../../../shared/asset-url'
import type { ImageItem } from '../lib/transcript'

/**
 * A picture the agent made, in the conversation (067).
 *
 * A generated picture may already be on disk even when its large event payload is dropped. Render the image from its recorded path instead of leaving only a collapsed activity marker.
 *
 * ⚠️ **The `<img>` never carries bytes.** `src` is a `brobot-asset:` URL the main process serves
 * from the file — see `shared/asset-url.ts` for why that scheme exists and why it cannot become a
 * navigation. Nothing here is base64, nothing here crosses IPC, and the 64 KiB payload ceiling is
 * untouched and irrelevant.
 */
const props = withDefaults(
  defineProps<{
    item: ImageItem
    /**
     * Whether this surface serves `brobot-asset:` URLs. Without a reader no picture is requested,
     * and the row says the picture isn't available here rather than that its file has moved.
     */
    canRead?: boolean
    /** Whether a press on the picture has somewhere to go; without it the picture is not a button. */
    canOpen?: boolean
  }>(),
  { canRead: true, canOpen: true },
)

const emit = defineEmits<{ open: [path: string] }>()

const src = computed(() => (props.canRead && props.item.path ? assetUrl(props.item.path) : null))

/** The file's own name, kept on screen where the picture can't be drawn. */
const fileName = computed(() => props.item.path?.split(/[\\/]/).pop() || null)

/**
 * The file was there when the event was recorded and is not there now (067, from its review).
 *
 * ⚠️ **This is the COMMON way an image goes missing, not the rare one.** The path is resolved once,
 * at emit time, and written into the ledger — and Codex's own image-generation skill then tells the
 * model to *move or copy* the file into the workspace for project work. So by the time anyone
 * re-reads the conversation, a path that was true is routinely stale. Without this the reader gets
 * a browser's broken-image glyph; with it they get the same honest sentence as an image that never
 * had a path at all, which is the same fact and deserves the same words.
 *
 * One-way: it never goes back to false. A `src` that failed once will fail again on every re-render
 * until the item itself is replaced, and flipping back would loop.
 */
const vanished = ref(false)
const shown = computed(() => src.value !== null && !vanished.value)

/**
 * The generation prompt as `alt`, falling back to a plain statement of what it is.
 *
 * Never empty, and never the filename: `alt` is read aloud, and `exec-297ad8c6-8e4e-403d.png` is
 * not a description of anything. The prompt is the only description the provider gives us.
 */
const alt = computed(() => props.item.prompt ?? 'an image generated by the agent')
</script>

<template>
  <figure class="image-entry" data-cy="image-entry" :data-image="item.imageId">
    <component
      :is="canOpen ? 'button' : 'div'"
      v-if="shown"
      class="frame"
      :type="canOpen ? 'button' : undefined"
      :data-cy="canOpen ? 'open-image' : 'image-frame'"
      :title="canOpen ? 'Open this image' : undefined"
      @click="canOpen && emit('open', item.path!)"
    >
      <!-- Sized by the layout, never by the file: a 1254×1254 PNG is wider than the column, and an
           intrinsic-size image would push the whole conversation sideways. `loading=lazy` because a
           long session can hold several and only the one on screen is worth fetching. -->
      <img
        class="shot"
        :src="src!"
        :alt="alt"
        loading="lazy"
        decoding="async"
        @error="vanished = true"
      />
    </component>

    <!-- No reader here: nothing is known about the file, so nothing is claimed about it. -->
    <p v-else-if="!canRead" class="missing" data-cy="image-unavailable">
      <svg class="icon"><use href="#i-alert" /></svg>
      <span>The agent generated an image, but this window can't show pictures.</span>
      <code v-if="fileName" class="file" data-cy="image-file-name">{{ fileName }}</code>
    </p>

    <!-- The file is gone, and that is a real outcome rather than a failure to hide: Codex's own
         image-generation skill tells the model to MOVE the file into the workspace for project
         work. Saying so beats a broken image icon, and beats pretending nothing happened. -->
    <p v-else class="missing" data-cy="image-missing">
      <svg class="icon"><use href="#i-alert" /></svg>
      <span>The agent generated an image, but its file is no longer where it was saved.</span>
    </p>

    <figcaption v-if="item.prompt" class="caption" data-cy="image-caption">
      {{ item.prompt }}
    </figcaption>
  </figure>
</template>

