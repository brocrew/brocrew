import { execFileSync } from 'node:child_process'
import {
  existsSync,
  lstatSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  rmSync,
  statSync,
  symlinkSync,
  truncateSync,
  writeFileSync,
} from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { afterEach, beforeEach, describe, expect, it } from 'vitest'
import {
  brobotWorkspace,
  ensureWorkspace,
  WORKSPACE_CANARY,
  workspaceInstructionFiles,
  workspaceOwnFilesIn,
} from '../src/main/runtime/workspace'
import { codexConventionChain, readSessionInstructions } from '../src/main/runtime/instructions'
import { resolveSessionCwd } from '../src/main/runtime/scratch-cwd'
import { legacyWorkspaceFiles } from './helpers/legacy-workspace-files'

const MODULE = new URL('../src/main/runtime/workspace.ts', import.meta.url).href

describe('the durable workspace without generated instructions', () => {
  let userData: string
  beforeEach(() => {
    userData = mkdtempSync(join(tmpdir(), 'brobot2-workspace-'))
  })
  afterEach(() => {
    rmSync(userData, { recursive: true, force: true })
  })

  it('creates only the folder and keeps it across conversations', () => {
    const workspace = ensureWorkspace(userData)
    expect(workspace).toBe(brobotWorkspace(userData))
    expect(readdirSync(workspace)).toEqual([])
    expect(workspaceInstructionFiles()).toEqual([])
    expect(workspaceOwnFilesIn(userData)).toEqual([])
    expect(resolveSessionCwd(userData, 'sess_1')).toBe(workspace)
    expect(resolveSessionCwd(userData, 'sess_2')).toBe(workspace)
    writeFileSync(join(workspace, 'notes.md'), 'still here')
    ensureWorkspace(userData)
    expect(readFileSync(join(workspace, 'notes.md'), 'utf8')).toBe('still here')
    expect(workspace).not.toContain('provider-homes')
  })

  for (const file of legacyWorkspaceFiles()) {
    it(`retires the previous generated ${file.name} once`, () => {
      const workspace = ensureWorkspace(userData)
      const path = join(workspace, file.name)
      writeFileSync(path, file.content)
      ensureWorkspace(userData)
      expect(existsSync(path)).toBe(false)
      ensureWorkspace(userData)
      expect(existsSync(path)).toBe(false)
    })
    for (const text of [
      '# My project rules\nLeave my files alone.\n',
      `Instruction marker: ${WORKSPACE_CANARY}\n`,
      file.content.replace(`Instruction marker: ${WORKSPACE_CANARY}`, 'My own ending'),
    ]) {
      it(`leaves a person-written ${file.name} unchanged without both ownership marks`, () => {
        const workspace = ensureWorkspace(userData)
        const path = join(workspace, file.name)
        writeFileSync(path, text)
        const before = statSync(path)
        ensureWorkspace(userData)
        expect(readFileSync(path, 'utf8')).toBe(text)
        expect(statSync(path).ino).toBe(before.ino)
        expect(statSync(path).mtimeMs).toBe(before.mtimeMs)
      })
    }
    it(`does not follow a symlink at ${file.name}, even to generated bytes`, () => {
      const workspace = ensureWorkspace(userData)
      const target = join(userData, 'outside.md')
      writeFileSync(target, file.content)
      symlinkSync(target, join(workspace, file.name))
      ensureWorkspace(userData)
      expect(lstatSync(join(workspace, file.name)).isSymbolicLink()).toBe(true)
      expect(readFileSync(target, 'utf8')).toBe(file.content)
    })
    it(`leaves a directory at ${file.name} alone`, () => {
      const workspace = ensureWorkspace(userData)
      mkdirSync(join(workspace, file.name))
      ensureWorkspace(userData)
      expect(lstatSync(join(workspace, file.name)).isDirectory()).toBe(true)
    })
    it(`does not read an oversized ${file.name}`, () => {
      const workspace = ensureWorkspace(userData)
      const path = join(workspace, file.name)
      writeFileSync(path, file.content)
      truncateSync(path, 64 * 1024 * 1024)
      ensureWorkspace(userData)
      expect(statSync(path).size).toBe(64 * 1024 * 1024)
    })
    it.skipIf(process.platform === 'win32')(
      `does not hang or remove a FIFO at ${file.name}`,
      () => {
        const workspace = ensureWorkspace(userData)
        const path = join(workspace, file.name)
        execFileSync('mkfifo', [path])
        execFileSync(
          process.execPath,
          [
            '--no-warnings',
            '--experimental-strip-types',
            '--input-type=module',
            '--eval',
            `const { ensureWorkspace } = await import(${JSON.stringify(MODULE)}); ensureWorkspace(process.argv[1])`,
            userData,
          ],
          { env: { ...process.env, ELECTRON_RUN_AS_NODE: undefined }, timeout: 10000 },
        )
        expect(lstatSync(path).isFIFO()).toBe(true)
      },
    )
  }

  it('refuses a symlinked workspace without changing its target', () => {
    const target = join(userData, 'outside')
    mkdirSync(target)
    for (const file of legacyWorkspaceFiles()) writeFileSync(join(target, file.name), file.content)
    symlinkSync(target, brobotWorkspace(userData))
    expect(() => ensureWorkspace(userData)).toThrow(/symlink/)
    for (const file of legacyWorkspaceFiles())
      expect(readFileSync(join(target, file.name), 'utf8')).toBe(file.content)
  })

  it('keeps an explicit project folder and its own instruction files', () => {
    const cwd = join(userData, 'project')
    mkdirSync(cwd)
    writeFileSync(join(cwd, 'CLAUDE.md'), 'PROJECT_CLAUDE_RULE')
    writeFileSync(join(cwd, 'AGENTS.md'), 'PROJECT_AGENTS_RULE')
    expect(resolveSessionCwd(userData, 'sess_1', cwd)).toBe(cwd)
    ensureWorkspace(userData)
    for (const provider of ['claude', 'codex'] as const) {
      const read = readSessionInstructions({
        provider,
        cwd,
        providerHome: join(userData, 'fictional-home'),
        home: userData,
        workspaceOwnFiles: workspaceOwnFilesIn(userData),
      })
      if (provider === 'claude') {
        expect(read.instructions.composed).toContain('PROJECT_CLAUDE_RULE')
        expect(read.instructions.composed).toContain('PROJECT_AGENTS_RULE')
      } else {
        expect(read.instructions.injected).toEqual([])
        expect(codexConventionChain(cwd, userData)).toContain(cwd)
      }
      expect(read.instructions.injected.every((one) => one.kind !== 'workspace-instructions')).toBe(
        true,
      )
    }
    expect(readFileSync(join(cwd, 'CLAUDE.md'), 'utf8')).toBe('PROJECT_CLAUDE_RULE')
    expect(readFileSync(join(cwd, 'AGENTS.md'), 'utf8')).toBe('PROJECT_AGENTS_RULE')
  })

  it('an upgraded default workspace contributes no retired body to either provider', () => {
    const workspace = ensureWorkspace(userData)
    for (const file of legacyWorkspaceFiles())
      writeFileSync(join(workspace, file.name), file.content)
    ensureWorkspace(userData)
    for (const provider of ['claude', 'codex'] as const) {
      const read = readSessionInstructions({
        provider,
        cwd: workspace,
        providerHome: join(userData, 'fictional-home'),
        home: userData,
        workspaceOwnFiles: workspaceOwnFilesIn(userData),
      })
      expect(read.instructions.injected).toEqual([])
      expect(read.instructions.composed ?? '').not.toContain(WORKSPACE_CANARY)
      expect(read.instructions.provider.map((one) => one.path)).not.toContain(
        join(workspace, 'AGENTS.md'),
      )
    }
  })
})
