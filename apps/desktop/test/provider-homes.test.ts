import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs'
import { tmpdir } from 'node:os'
import { basename, dirname, join } from 'node:path'
import { afterEach, beforeEach, describe, expect, it } from 'vitest'
import { AuthUnavailableError } from '@brobot2/runtime'
import {
  DEFAULT_PROFILE_ID,
  HOME_FOLDER,
  createProviderRuntime,
  deriveProviderHome,
  listProfileIds,
  prepareProviderHome,
  providerHomesRoot,
} from '../src/main/runtime/provider-homes'
import { PATH_SEGMENT_MAX_LENGTH, isPathSegment } from '../src/shared/runtime-ipc'
import { whoElseCanOpen } from '../../../scripts/lib/readable-only-by-this-user.mjs'

/**
 * The app-layer half of provider-home isolation. The credential seams are injected
 * throughout: this suite never reads the machine Keychain or the personal
 * `~/.codex`.
 */
describe('provider homes', () => {
  let userData: string

  const identity = {
    profileId: DEFAULT_PROFILE_ID,
    provider: 'claude' as const,
  }

  beforeEach(() => {
    userData = mkdtempSync(join(tmpdir(), 'brobot2-homes-'))
  })

  afterEach(() => {
    rmSync(userData, { recursive: true, force: true })
  })

  /**
   * ⛔ 168 L2 · 160's migration reaches a home nothing ever LAUNCHES in (188 §1).
   *
   * The adapter clears a stale 157 `config.toml` on `start` and on `resume`, which covers every home
   * that gets relaunched and no home that does not. A profile the user only ever adopted sessions
   * into — or one whose conversations have all ended — kept a deny-list over `~/.claude`, `~/.codex`
   * and `userData` under a header calling itself *"rewritten on every session launch"*. This is the
   * one function every Codex home passes through.
   */
  describe('a stale 157 permissions block (168 L2)', () => {
    const codex = {
      profileId: DEFAULT_PROFILE_ID,
      provider: 'codex' as const,
    }
    const seams = { provisionCodexAuth: () => {} }
    const STALE = '# Generated by BroBot2 — rewritten on every session launch. Do not edit.\n[x]\n'

    it('is removed when the home is merely PREPARED, with no launch anywhere near it', async () => {
      // ⚠️ **Corrected in place at 314.** This used to assert the file was ABSENT afterwards. There
      // is a `config.toml` here again now, because the same function that removes 157's block goes
      // on to write the memory gates — so the assertion asks what it was always asking: is the
      // BLOCK gone.
      const home = await prepareProviderHome(userData, codex, seams)
      writeFileSync(join(home, 'config.toml'), STALE)

      expect(await prepareProviderHome(userData, codex, seams)).toBe(home)
      const after = readFileSync(join(home, 'config.toml'), 'utf8')
      expect(after, 'nothing launched, and it is gone').not.toContain('# Generated by BroBot2')
      expect(after, "…and this home's gates were written by the same call").toContain(
        'memories = true',
      )
    })

    it('…and a config this app did not write is MERGED into, never deleted or replaced', async () => {
      // ⚑ The paired positive. The fail-safe is the generated header, not the filename: "delete a
      // config file out of a Codex home" is the operation that must never be approximate.
      //
      // ⛔ **314 corrected the title and the assertion.** *"Left exactly where it is"* compared the
      // whole file byte-for-byte, which was true while this app wrote nothing into it. What the
      // fail-safe promises is unchanged and is what is asserted now: somebody else's entries are all
      // still here — the property 312 measured a whole-file rewrite destroying.
      const home = await prepareProviderHome(userData, codex, seams)
      const theirs = "# somebody else's\n[permissions.deny]\nfoo = 1\n"
      writeFileSync(join(home, 'config.toml'), theirs)

      await prepareProviderHome(userData, codex, seams)
      const after = readFileSync(join(home, 'config.toml'), 'utf8')
      expect(after).toContain("# somebody else's")
      expect(after).toContain('[permissions.deny]\nfoo = 1')
      expect(after).toContain('dedicated_tools = true')
    })

    it('🔴 …and a home with NO config gets one — the ordinary case for every profile today', async () => {
      // A Codex home can lack `config.toml`, including a profile only adopted and never
      // started or resumed. `provisionProviderHome` is the common path for every Codex home,
      // so the fixture must cover that state there.
      const home = await prepareProviderHome(userData, codex, seams)
      const written = readFileSync(join(home, 'config.toml'), 'utf8')
      for (const key of ['memories', 'dedicated_tools', 'use_memories', 'generate_memories']) {
        expect(written, `${key} is not switched on in a freshly prepared home`).toContain(
          `${key} = true`,
        )
      }
      // ⛔ …and it must not carry the header that arms our own stale sweep against it.
      expect(written.startsWith('# Generated by BroBot2')).toBe(false)
      expect(await prepareProviderHome(userData, codex, seams)).toBe(home)
      expect(readFileSync(join(home, 'config.toml'), 'utf8')).toBe(written)
    })

    it('does not touch a CLAUDE home, which has no such file to migrate', async () => {
      const home = await prepareProviderHome(userData, identity, {
        claudeAuthHealth: () => ({ ok: true }) as never,
      })
      writeFileSync(join(home, 'config.toml'), STALE)

      await prepareProviderHome(userData, identity, {
        claudeAuthHealth: () => ({ ok: true }) as never,
      })
      expect(existsSync(join(home, 'config.toml')), "Codex's migration, in Codex homes").toBe(true)
      // ⚑ …and 314's gates are not written into a Claude home either. Claude's memory is a
      // `Settings.autoMemoryDirectory` this app passes per launch, not a file in a TOML table.
      expect(readFileSync(join(home, 'config.toml'), 'utf8')).toBe(STALE)
    })
  })

  it('derives one home per profile and provider, all in the one folder under the managed root', () => {
    expect(deriveProviderHome(userData, identity)).toBe(
      join(providerHomesRoot(userData), HOME_FOLDER, DEFAULT_PROFILE_ID, 'claude'),
    )
    expect(deriveProviderHome(userData, { ...identity, provider: 'codex' })).toBe(
      join(providerHomesRoot(userData), HOME_FOLDER, DEFAULT_PROFILE_ID, 'codex'),
    )
    // ⛔ D-016 · the folder is spelled as the LITERAL here, not through the constant: every home on
    // disk was made under `default`, so a change to that name would resume every conversation into
    // a home it never ran in — and a profile other than BroBot's lands in the same folder.
    expect(deriveProviderHome(userData, { ...identity, profileId: 'dev' })).toBe(
      join(providerHomesRoot(userData), 'default', 'dev', 'claude'),
    )
  })

  it.each(['..', 'a/b', '', '.hidden', 'has space', '/abs'])(
    'refuses the id %p rather than letting it become a path',
    (profileId) => {
      expect(() => deriveProviderHome(userData, { ...identity, profileId })).toThrow(
        /invalid profileId/,
      )
    },
  )

  it('provisions the home for a healthy Claude login', async () => {
    const home = await prepareProviderHome(userData, identity, {
      claudeAuthHealth: () => ({ ok: true }),
    })

    expect(home).toBe(deriveProviderHome(userData, identity))
    expect(statSync(home).isDirectory()).toBe(true)
    expect(whoElseCanOpen(home, 0o700)).toEqual([])
  })

  it('fails closed when the Claude machine login is unavailable', async () => {
    await expect(
      prepareProviderHome(userData, identity, {
        claudeAuthHealth: () => ({ ok: false, reason: 'expired' }),
      }),
    ).rejects.toThrow(AuthUnavailableError)
    await expect(
      prepareProviderHome(userData, identity, {
        claudeAuthHealth: () => ({ ok: false, reason: 'expired' }),
      }),
    ).rejects.toThrow('expired')
  })

  it('copies the Codex credential into the home it just provisioned', async () => {
    const provisioned: string[] = []
    const home = await prepareProviderHome(
      userData,
      { ...identity, provider: 'codex' },
      { provisionCodexAuth: (path) => void provisioned.push(path) },
    )

    expect(provisioned).toEqual([home])
    expect(statSync(home).isDirectory()).toBe(true)
  })

  /**
   * ⛔ **Both provisioning seams are AWAITED, not merely called** (243).
   *
   * They became promise-returning when the lock's wait stopped blocking the thread — and a seam
   * typed `=> void` accepts a `=> Promise<void>` implementation under TypeScript's void-return
   * bivariance, then drops the promise. ⚠️ **The whole tree still compiles**, with this function
   * handing back a home whose directory does not exist yet and whose credential has not been copied.
   * There are no type-aware lint rules here to have caught it, so this test is the only thing that
   * does. An uncontended real provisioning cannot tell the difference — the lock runs synchronously
   * as far as its own body — so the seams are made slow on purpose.
   */
  it('⛔ waits for BOTH provisioning seams before it hands the home back (243)', async () => {
    const finished: string[] = []
    // ⚠️ **Different durations, and that is the whole test.** With two equally slow seams both land
    // inside the second one's wait even when the first is not awaited, and the row survives.
    const slow = (label: string, ms: number) => async () => {
      await new Promise((resolve) => setTimeout(resolve, ms))
      finished.push(label)
    }

    const home = await prepareProviderHome(
      userData,
      { ...identity, provider: 'codex' },
      { provisionHome: slow('provision', 60), provisionCodexAuth: slow('auth', 5) },
    )

    expect(finished, 'it returned before its own provisioning had finished').toEqual([
      'provision',
      'auth',
    ])
    expect(home).toBe(deriveProviderHome(userData, { ...identity, provider: 'codex' }))
  })

  it('provisions before it authenticates, so a credential is never written outside a managed home', async () => {
    const order: string[] = []
    await prepareProviderHome(
      userData,
      { ...identity, provider: 'codex' },
      {
        provisionHome: () => void order.push('provision'),
        provisionCodexAuth: () => void order.push('auth'),
      },
    )
    expect(order).toEqual(['provision', 'auth'])
  })

  it('builds the adapter that matches the provider — and only codex asks for the bundled binary', () => {
    // The command is a thunk resolved per codex launch (014). Claude must never invoke it: a
    // missing codex binary is a codex problem, and a claude session that tripped over it would
    // couple the two providers' availability.
    let asked = 0
    const seams = {
      codexCommand: () => {
        asked += 1
        return '/bundled/bin/codex'
      },
      claudeProgram: () => '/installed/bin/claude',
    }
    expect(createProviderRuntime('claude', seams).provider).toBe('claude')
    expect(asked).toBe(0)
    expect(createProviderRuntime('codex', seams).provider).toBe('codex')
    expect(asked).toBe(1)
  })

  it('a codexCommand that throws surfaces as the launch error, not a half-built runtime', () => {
    expect(() =>
      createProviderRuntime('codex', {
        codexCommand: () => {
          throw new Error("Codex isn't available — test")
        },
        claudeProgram: () => '/installed/bin/claude',
      }),
    ).toThrow(/Codex isn't available/)
  })

  /**
   * 🔴 **Which profiles exist** (167) — the launcher's menu, and the only source it has.
   *
   * There is no registry: a profile is a directory under the managed root, created on first use. So
   * these assertions are about a directory listing behaving like a menu — never empty, the default
   * first, and refusing to name a home the launcher could not actually open.
   */
  describe('the profiles a person can choose (167)', () => {
    /** Lay a home down the way `prepareProviderHome` does, without a credential seam in sight. */
    function plant(profileId: string, provider: string): void {
      mkdirSync(join(providerHomesRoot(userData), HOME_FOLDER, profileId, provider), {
        recursive: true,
      })
    }

    it('answers with BroBot alone before anything has ever been created', () => {
      // The fresh-install case, and the one a `readdir` would throw on: there is no
      // `provider-homes` directory at all yet. "No profiles" would be a false report of an app whose
      // main agent you can start a conversation with right now.
      expect(listProfileIds(userData)).toEqual([DEFAULT_PROFILE_ID])
    })

    it('reads the homes back, default first and the rest sorted', () => {
      plant('writer', 'claude')
      plant(DEFAULT_PROFILE_ID, 'claude')
      plant('developer', 'codex')
      // Two providers under one profile is ONE profile — the menu is about agents, not homes.
      plant('developer', 'claude')

      expect(listProfileIds(userData)).toEqual([DEFAULT_PROFILE_ID, 'developer', 'writer'])
    })

    it('names the default once, whether or not its home is on disk', () => {
      // The two ways `default` can arrive — planted and not — must produce one row, and it must be
      // the first one. A second `default` in the menu would be two rows that open the same home.
      plant(DEFAULT_PROFILE_ID, 'claude')
      expect(listProfileIds(userData)).toEqual([DEFAULT_PROFILE_ID])

      plant('aardvark', 'claude')
      expect(listProfileIds(userData), 'default leads, it is not sorted into place').toEqual([
        DEFAULT_PROFILE_ID,
        'aardvark',
      ])
    })

    it('⛔ leaves out a profile in a folder beside `default`, which is a home this launcher cannot open', () => {
      plant('developer', 'claude')
      // ⚑ A well-formed home in every respect but its folder — the shape a project segment left.
      mkdirSync(join(providerHomesRoot(userData), 'aurora', 'painter', 'claude'), {
        recursive: true,
      })

      // D-016: every launch is under the one home folder. Offering `painter` would name a directory
      // that choosing it would NOT open — the launch would provision a second `painter` under
      // `default` instead, which is the silent-extra-home failure arriving from the one direction
      // the user could not have caused.
      expect(listProfileIds(userData)).toEqual([DEFAULT_PROFILE_ID, 'developer'])
    })

    it('ignores anything under the root that is not a home this app would have laid down', () => {
      plant('developer', 'claude')
      // A directory whose name could never be a profile id, and one whose provider is not a
      // provider. Neither is a home this app made, and guessing an identity for either would offer a
      // row that cannot be launched.
      mkdirSync(join(providerHomesRoot(userData), HOME_FOLDER, '..hidden', 'claude'), {
        recursive: true,
      })
      plant('orphan', 'notaprovider')
      // …and a FILE where a directory would be.
      writeFileSync(join(providerHomesRoot(userData), HOME_FOLDER, 'a-file'), 'x')

      const listed = listProfileIds(userData)
      expect(listed).toContain('developer')
      expect(listed, 'a directory with no provider under it is not a profile').not.toContain(
        'orphan',
      )
      expect(listed).not.toContain('..hidden')
      expect(listed).not.toContain('a-file')
    })

    /**
     * ⚠️ **The round-trip 167 §1.3 asks for, and it is the assertion the alphabet rule is FOR.**
     *
     * A name is legal because it can be a directory. So every name `isPathSegment` accepts has to
     * come back off the path unchanged — otherwise the profile the user named and the profile on
     * disk are two different things, and the recorded id would resume into a home that is not theirs.
     */
    it('every name the rule accepts survives becoming a directory and being read back', () => {
      for (const profileId of [
        DEFAULT_PROFILE_ID,
        'developer',
        'client-2',
        'a.b_c',
        'A',
        '9lives',
        'x'.repeat(PATH_SEGMENT_MAX_LENGTH),
      ]) {
        expect(isPathSegment(profileId), profileId).toBe(true)
        const home = deriveProviderHome(userData, { ...identity, profileId })
        // The profile is the segment ABOVE the provider, and it is byte-for-byte what was asked for.
        expect(basename(dirname(home)), profileId).toBe(profileId)

        plant(profileId, 'claude')
        expect(listProfileIds(userData), profileId).toContain(profileId)
      }
    })
  })
})
