import { createSSRApp, h } from 'vue'
import { renderToString } from 'vue/server-renderer'
import type { TranscriptEvent } from '../src/shared/runtime-ipc'
import { ASSET_SCHEME } from '../src/shared/asset-url'
import ImageEntry from '../src/renderer/src/components/ImageEntry.vue'
import ImageViewer from '../src/renderer/src/components/ImageViewer.vue'
import SessionPanel from '../src/renderer/src/components/SessionPanel.vue'
import TranscriptView from '../src/renderer/src/components/TranscriptView.vue'
import { sessionPanel } from '../src/renderer/src/lib/session-panel'
import {
  applyEvent,
  createTranscript,
  type ImageItem,
  type TranscriptState,
} from '../src/renderer/src/lib/transcript'
import { isVisibleIn } from '../src/renderer/src/lib/transcript-mode'

/**
 * The image, on screen (067).
 *
 * This `.render.test.ts` imports SFCs to assert that a generated image renders from its file
 * rather than an embedded payload, and that the Assets index names it.
 *
 * ⚠️ What it deliberately does not claim: that the bytes arrive. There is no protocol handler in an
 * SSR render and no network of any kind — the `src` is asserted, and whether the main process
 * serves it is `asset-protocol.test.ts`'s job and the live smoke's. Two halves, neither pretending
 * to be the other.
 */

const PATH =
  '/Users/x/Library/Application Support/@brobot2/desktop/provider-homes/default/default/codex/generated_images/019fcfb1/exec-297ad8c6.png'
const PROMPT = 'a tiny, cheerful minimalist illustration of a curled-up red fox'

async function render(component: unknown, props: Record<string, unknown>): Promise<string> {
  return renderToString(createSSRApp({ render: () => h(component as never, props) }))
}

function withImage(
  event: Partial<Extract<TranscriptEvent, { type: 'image' }>> = {},
): TranscriptState {
  const state = createTranscript()
  applyEvent(state, { type: 'image', imageId: 'exec-297ad8c6', ...event } as TranscriptEvent)
  return state
}

describe('ImageEntry — the picture in the conversation (067 acceptance 2)', () => {
  it('renders an <img> whose src is the asset scheme, not the file path and not base64', () => {
    const item: ImageItem = { kind: 'image', id: 'image-1', imageId: 'exec-1', path: PATH }
    return render(ImageEntry, { item }).then((html) => {
      expect(html).toContain(`src="${ASSET_SCHEME}://`)
      // ⚠️ The two things the dispatch forbids, asserted as absences. `data:` would be the base64
      // it says not to decode; `file:` would be the scheme 050 exists to keep out of this document.
      expect(html).not.toContain('data:image')
      expect(html).not.toContain('file://')
      // The path is percent-encoded into one segment, so the raw spaces of "Application Support"
      // must not appear in the attribute.
      expect(html).not.toContain('Application Support/')
    })
  })

  it('uses the generation prompt as alt text and as a caption', async () => {
    const item: ImageItem = { kind: 'image', id: 'i', imageId: 'e', path: PATH, prompt: PROMPT }
    const html = await render(ImageEntry, { item })
    expect(html).toContain(`alt="${PROMPT}"`)
    expect(html).toContain('data-cy="image-caption"')
  })

  it('never has an empty alt — a filename is not a description', async () => {
    const item: ImageItem = { kind: 'image', id: 'i', imageId: 'e', path: PATH }
    const html = await render(ImageEntry, { item })
    expect(html).toContain('alt="an image generated by the agent"')
    expect(html).not.toContain('alt=""')
  })

  it('⚠️ says the file is gone rather than rendering a broken image', async () => {
    // Codex's own image-generation skill tells the model to MOVE the file into the workspace for
    // project work, so this is an ordinary outcome and not an error state.
    const item: ImageItem = { kind: 'image', id: 'i', imageId: 'e', prompt: PROMPT }
    const html = await render(ImageEntry, { item })
    expect(html).toContain('data-cy="image-missing"')
    expect(html).toContain('no longer where it was saved')
    expect(html).not.toContain('<img')
    // Not a button either: there is nothing to open, and a control that does nothing when pressed
    // is the thing this codebase keeps deleting.
    expect(html).not.toContain('data-cy="open-image"')
  })
})

describe('the review\u2019s renderer findings (067)', () => {
  it('the panel draws no empty paragraph over a populated Assets list', async () => {
    // Two true things that read as a contradiction: `empty` is a statement about WORK and stays
    // true beside a list of assets, but the paragraph goes on to enumerate what appears here and
    // assets are not in that list.
    const state = withImage({ path: PATH })
    expect(sessionPanel(state).empty).toBe(true)
    const html = await render(SessionPanel, { state, mode: 'normal' })
    expect(html).toContain('data-cy="panel-assets"')
    expect(html).not.toContain('data-cy="session-panel-empty"')
  })

  it('model-authored markdown cannot reach the asset scheme', async () => {
    // `brobot-asset:` serves any image file a URL names, wherever it is (`726` · R92), so an
    // agent-authored `![](brobot-asset://\u2026)` would render an <img> of ANY image on this machine.
    // markdown-it allows every scheme it does not name, so this one had to be named.
    const { renderChatMarkdown, renderMarkdown } = await import('../src/renderer/src/lib/markdown')
    const evil = `![](brobot-asset://file/${encodeURIComponent(PATH)})`
    for (const render of [renderChatMarkdown, renderMarkdown]) {
      const html = render(evil)
      // The property is that no `<img src>` is PRODUCED. markdown-it leaves the refused link as
      // ordinary escaped text, which is exactly right — the reader sees what the agent wrote and
      // the renderer fetches nothing.
      expect(html).not.toContain('<img')
      expect(html).not.toContain('src=')
    }
    // Non-vacuity: an image destination that CAN still render does, so the block above is about
    // the scheme rather than about images.
    //
    // ⚠️ This assertion used to use `https://example.com/a.png`, and 071 is why it cannot any more:
    // a remote image is a click-free outbound request (069 finding 2), so the only destination this
    // renderer will still turn into an `<img>` is an inline `data:image/…`, which is already in the
    // document and fetches nothing.
    expect(renderChatMarkdown('![alt](data:image/png;base64,iVBORw0KGgo=)')).toContain('<img')
  })
})

describe('the transcript shows it, in the mode a user actually reads (067)', () => {
  it('renders an image entry through the real fold and the real dispatch table', async () => {
    const state = withImage({ path: PATH, prompt: PROMPT })
    const html = await render(TranscriptView, { items: state.items, mode: 'normal' })
    expect(html).toContain('data-cy="image-entry"')
    expect(html).toContain(`src="${ASSET_SCHEME}://`)
    // NOT the chatter line it used to be. This is the regression that matters: before 067 the same
    // event rendered as `activity · imageGeneration` and `normal` mode hid it entirely.
    expect(html).not.toContain('data-cy="chatter-entry"')
  })

  it('is visible in normal mode — where it was invisible before', () => {
    const state = withImage({ path: PATH })
    const item = state.items[0]!
    expect(item.kind).toBe('image')
    expect(isVisibleIn('normal', item)).toBe(true)
    expect(isVisibleIn('debug', item)).toBe(true)
  })
})

describe('the Assets index (067 acceptance 3)', () => {
  it('lists an image that has a file, with its name and what it was made from', async () => {
    const state = withImage({ path: PATH, prompt: PROMPT })
    expect(sessionPanel(state).assets).toEqual([
      {
        key: 'image_1',
        itemId: 'image_1',
        path: PATH,
        name: 'exec-297ad8c6.png',
        prompt: PROMPT,
      },
    ])
    const html = await render(SessionPanel, { state, mode: 'normal' })
    expect(html).toContain('data-cy="panel-assets"')
    expect(html).toContain('exec-297ad8c6.png')
  })

  it('⚠️ does NOT list an image whose file is gone — an index of unopenable things is worse', () => {
    const state = withImage({ prompt: PROMPT })
    expect(sessionPanel(state).assets).toEqual([])
    // …while the conversation still shows it. The two surfaces are saying different true things,
    // not disagreeing: one is "this happened", the other is "you can open this".
    expect(state.items).toHaveLength(1)
  })

  it('has no Assets section at all when the session made nothing', async () => {
    const html = await render(SessionPanel, { state: createTranscript(), mode: 'normal' })
    expect(html).not.toContain('data-cy="panel-assets"')
    expect(html).toContain('data-cy="session-panel"')
  })

  it('assets do not count as things waiting on you', () => {
    // 037's badge counts what is blocked on the user. An asset never settles, so counting it would
    // light the badge for the rest of the conversation — which is what that rule already refuses
    // to do for running agents.
    const panel = sessionPanel(withImage({ path: PATH }))
    expect(panel.waiting).toBe(0)
    expect(panel.empty).toBe(true)
    expect(panel.assets).toHaveLength(1)
  })
})

describe('the viewer, opened from either entrance (067)', () => {
  it('shows the file at its own name, on paper, with the whole prompt', async () => {
    const html = await render(ImageViewer, { path: PATH, prompt: PROMPT })
    expect(html).toContain('data-cy="image-viewer"')
    expect(html).toContain('exec-297ad8c6.png')
    expect(html).toContain(`src="${ASSET_SCHEME}://`)
    expect(html).toContain('data-cy="viewer-prompt"')
  })

  it('has a close control, so the overlay is never a trap', async () => {
    const html = await render(ImageViewer, { path: PATH })
    expect(html).toContain('data-cy="close-overlay"')
  })
})
