"""The immutable per-table mutation-runner shim contract.

The shim is deliberately smaller than the contract it invokes. Future runner changes belong in
``run-table.sh``; a table branch that carries this unchanged shim therefore picks up the target
branch's current driver when it is integrated.
"""

from __future__ import annotations

import re

RUNNER_SHIM_VERSION = "v1"
# 314 was already in flight when this contract landed. Numeric dispatch ids are monotonic, so 315
# is the explicit boundary after which a copied inline runner is never accepted.
SHIM_REQUIRED_FROM = 315
SHIM_MARKER = (
    "# mutation-runner-shim v1 — executable body below is generated; "
    "keep table evidence above this line"
)
SHIM_EXECUTABLE_LINES = (
    "set -uo pipefail",
    'MUTATION_TABLE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"',
    'exec "$MUTATION_TABLE_DIR/../lib/run-table.sh" "$MUTATION_TABLE_DIR" "$@"',
)
SHIM_SUFFIX = "\n".join((SHIM_MARKER, *SHIM_EXECUTABLE_LINES)) + "\n"
TABLE_ID = re.compile(r"[1-9][0-9]*")


def runner_shim_problem(source: str) -> str | None:
    """Return why ``source`` is not the exact shim, or ``None`` when it is."""

    if not source.startswith("#!/usr/bin/env bash\n"):
        return "first line must be `#!/usr/bin/env bash`"
    if source.count(SHIM_MARKER) != 1:
        return f"expected exactly one `{SHIM_MARKER}` marker"
    if not source.endswith(SHIM_SUFFIX):
        return "executable suffix differs from the generated runner shim"
    prefix = source[: -len(SHIM_SUFFIX)]
    for number, line in enumerate(prefix.splitlines()[1:], start=2):
        if line.strip() and not line.lstrip().startswith("#"):
            return f"line {number} contains executable code before the generated shim"
    return None


def render_runner(table: str) -> str:
    """Render a new table's complete stable shim."""

    if TABLE_ID.fullmatch(table) is None:
        raise ValueError(f"table id must be a positive decimal integer: {table}")
    prefix = "\n".join(
        (
            "#!/usr/bin/env bash",
            "#",
            f"# {table} · mutation runner.",
            "#",
            "# Generated by scripts/mutations/scaffold.py. Put table-specific evidence in",
            "# comments above the marker or in mutations.py; do not edit the executable shim.",
        )
    )
    return f"{prefix}\n#\n{SHIM_SUFFIX}"
