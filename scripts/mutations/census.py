def source_view(path: pathlib.Path) -> pathlib.Path:
    """Return the proved pristine view for one active row target, or the live path."""

    resolved = path.resolve()
    viewed = _ACTIVE_SOURCE_VIEW.get(resolved)
    if viewed is None:
        return path
    expected = _ACTIVE_LIVE_SHA256[resolved]
    if path.is_symlink() or not path.is_file():
        raise ValueError(f"active mutation target changed shape after proof: {path}")
    actual = hashlib.sha256(path.read_bytes()).hexdigest()
    if actual != expected:
        raise ValueError(f"active mutation target changed after proof: {path}")
    return viewed


def _repo_label(path: pathlib.Path) -> str:
    try:
        return path.relative_to(REPO).as_posix()
    except ValueError:
        return path.as_posix()


def _expanded_runner_contract_violations(
    path: pathlib.Path, source: str
) -> list[tuple[str, str, str]]:
    """Validate one grandfathered inline runner or the one shared current driver."""

    label = _repo_label(path)
    violations: list[tuple[str, str, str]] = []
    lines = source.splitlines()
    executable = [line for line in lines if not line.lstrip().startswith("#")]
    legacy_count = sum(line.strip() == _RUNNER_LEGACY_TAIL for line in executable)
    if legacy_count:
        violations.append(
            (
                label,
                "runner-legacy-direct-log",
                f"found {legacy_count} direct canonical-log tail(s); atomic partial required",
            )
        )
    for rule, required in _RUNNER_REQUIRED_LINES:
        count = lines.count(required)
        if count != 1:
            violations.append(
                (label, rule, f"expected exactly one `{required}` line, found {count}")
            )
    header_count = source.count(_RUNNER_HEADER_BLOCK)
    if header_count != 1:
        violations.append(
            (
                label,
                "runner-reachability-header-count",
                f"expected one timestamp/reachability header block, found {header_count}",
            )
        )
    expected_tail = (
        _RUNNER_PINNED_ATOMIC_TAIL
        if path == HERE / "lib/run-table.sh"
        else _RUNNER_ATOMIC_TAIL
    )
    tail_count = source.count(expected_tail)
    if tail_count != 1:
        violations.append(
            (
                label,
                "runner-atomic-tail-count",
                f"expected one atomic PIPESTATUS/publish tail, found {tail_count}",
            )
        )
    return violations


def _runner_contract_violations() -> list[tuple[str, str, str]]:
    """Return live runner defects before an artefact can be written or blessed.

    Historical inline runners remain replayable and retain the exact hook audit introduced by 311.
    New runners are generated immutable shims: all evolving behavior lives in run-table.sh, so a
    table branch automatically uses the integration branch's current contract.
    """

    violations: list[tuple[str, str, str]] = []
    definition_dirs: set[pathlib.Path] = set()
    runner_paths: set[pathlib.Path] = set()
    for table in HERE.iterdir():
        if table.is_symlink():
            if TABLE_ID.fullmatch(table.name):
                violations.append(
                    (
                        _repo_label(table),
                        "table-directory-symlink",
                        "numeric mutation table directories must not be symlinks",
                    )
                )
            continue
        if not table.is_dir():
            continue
        definition = table / "mutations.py"
        runner = table / "mutate.sh"
        if definition.exists() or definition.is_symlink():
            definition_dirs.add(table)
        if runner.exists() or runner.is_symlink():
            runner_paths.add(runner)
    runner_dirs = {path.parent for path in runner_paths}

    for table in sorted(definition_dirs - runner_dirs):
        violations.append(
            (
                _repo_label(table / "mutate.sh"),
                "runner-missing",
                "mutations.py has no replayable mutate.sh",
            )
        )
    for table in sorted(runner_dirs - definition_dirs):
        violations.append(
            (
                _repo_label(table / "mutate.sh"),
                "runner-orphan",
                "mutate.sh has no mutations.py definition",
            )
        )

    driver = HERE / "lib/run-table.sh"
    if driver.is_symlink() or not driver.is_file():
        violations.append(
            (
                _repo_label(driver),
                "runner-driver-missing",
                "the current shared table driver must be a regular, non-symlink file",
            )
        )
    else:
        if not os.access(driver, os.X_OK):
            violations.append(
                (
                    _repo_label(driver),
                    "runner-not-executable",
                    "the current shared table driver must be executable",
                )
            )
        violations.extend(
            _expanded_runner_contract_violations(
                driver, driver.read_text(errors="replace")
            )
        )

    for runner in sorted(runner_paths):
        label = _repo_label(runner)
        if runner.is_symlink() or not runner.is_file():
            violations.append(
                (label, "runner-not-regular", "runner must be a regular, non-symlink file")
            )
            continue
        if not os.access(runner, os.X_OK):
            violations.append(
                (label, "runner-not-executable", "runner must be executable")
            )
        if TABLE_ID.fullmatch(runner.parent.name) is None:
            violations.append(
                (label, "runner-table-id-invalid", "runner directory must be a decimal table id")
            )
            continue
        table_id = int(runner.parent.name)
        source = runner.read_text(errors="replace")
        shim_problem = runner_shim_problem(source)
        if shim_problem is None:
            continue
        if SHIM_MARKER in source:
            violations.append((label, "runner-shim-invalid", shim_problem))
            continue
        if table_id >= SHIM_REQUIRED_FROM:
            violations.append(
                (
                    label,
                    "runner-not-scaffolded",
                    "new tables must use scripts/mutations/scaffold.py; "
                    "copied inline runners are not accepted",
                )
            )
            continue
        violations.extend(_expanded_runner_contract_violations(runner, source))
    return violations


def _definition_contract_violations() -> list[tuple[str, str, str]]:
    """Validate definitions without importing them or following table/definition symlinks."""

    violations: list[tuple[str, str, str]] = []
    for table in sorted(HERE.iterdir()):
        if table.is_symlink() or not table.is_dir():
            continue
        definition = table / "mutations.py"
        if not (definition.exists() or definition.is_symlink()):
            continue
        label = _repo_label(definition)
        if definition.is_symlink() or not definition.is_file():
            violations.append(
                (
                    label,
                    "definition-not-regular",
                    "mutations.py must be a regular, non-symlink file",
                )
            )
            continue
        try:
            rows = load_table(definition)
            runner = table / "mutate.sh"
            source = (
                runner.read_text(errors="replace")
                if not runner.is_symlink() and runner.is_file()
                else ""
            )
            uses_shared_adapter = runner_shim_problem(source) is None
            if uses_shared_adapter or (
                TABLE_ID.fullmatch(table.name) is not None
                and int(table.name) >= SHIM_REQUIRED_FROM
            ):
                validate_authority(rows, REPO)
        except (OSError, UnicodeError, ValueError) as error:
            violations.append((label, "definition-contract", str(error)))
    return violations


def _without_comment_only_lines(source: str, javascript: bool) -> str:
    """Blank comments while preserving line numbers and generated-shell template text."""

    kept: list[str] = []
    in_block_comment = False
    for line in source.splitlines():
        stripped = line.lstrip()
        if not javascript:
            kept.append("" if stripped.startswith("#") else line)
            continue
        if in_block_comment:
            if "*/" in stripped:
                in_block_comment = False
                suffix = stripped.split("*/", 1)[1]
                kept.append(suffix if suffix.strip() else "")
            else:
                kept.append("")
            continue
        if stripped.startswith("//"):
            kept.append("")
            continue
        if stripped.startswith("/*"):
            if "*/" in stripped:
                suffix = stripped.split("*/", 1)[1]
                kept.append(suffix if suffix.strip() else "")
            else:
                in_block_comment = True
                kept.append("")
            continue
        kept.append(line)
    return "\n".join(kept)


