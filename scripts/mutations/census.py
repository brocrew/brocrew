#!/usr/bin/env python3
"""Census every recorded mutation table against the tree as it is NOW.

⛔ WHY THIS EXISTS (188 §1, from 168 M7 / 168 L6 / 182 L5)

A mutation row is evidence: "delete this exact text and these tests go red". The evidence is only
worth the anchor — the FIXED text the row searches for. When the code moves, the anchor stops
matching, `mutate.sh` reports DID NOT APPLY, and the row protects nothing. Nothing said so.

168 M7 named three such rows. 182 checked the 169-181 tables and found all 113 anchors intact. At
188 the real number across every table is far larger, and six of 182's own 113 had gone stale in the
six dispatches since it looked — which is the finding rather than the three rows: **a mutation
artefact is a historical claim, and nothing was measuring how much of it still described the tree.**

⚠️ THIS TOOL DOES NOT RE-RUN ANYTHING. It cannot: re-running 497 rows is days of test time. It
answers the two questions that can be answered cheaply and that everything else rests on — *can this
row still apply, and does every declared edit change bytes?* A row that cannot apply is retired in
place (142's rule: correct, never delete), named here, and known to be protecting nothing.

⚑ AND IT PINS THE FILES. Each table records the SHA-256 of every file it touches, so a later reader
can tell whether the recorded RED still describes the code it was recorded against — 168 L6's
complaint about 166's artefact, generalized to all of them.

⛔ AND A RETIREMENT IS ANNOUNCED, NEVER ABSORBED (528 §1, from HO-050 §3)

The paragraph above was true and the tool was still able to go quiet. `523 M15`'s anchor quoted an
ending button as `523` found it; the merge with `520` rewrote that button; the integrator
regenerated; `CENSUS.md` recorded `523 | 15 | 14 | 1` with `- 523 M15` in a list of three hundred,
and `--check` passed. **Nothing said a row had stopped measuring.** The PO's ruling: *"Retirement is
reported. A census that counts retired rows and stays green is reporting a number it is not
measuring."*

The five questions 528 was sent with, answered here because this is the docblock a reader of the
rail lands on.

⚑ **Q1 · What is `loud`, and what is it loud SINCE.** Not red: 311 rows were already retired when
this landed and reddening them makes the gate unpassable, which is not the ask. Loud means a
row going retired **since the census on disk** — `CENSUS.md` + `ATTESTATION.json` as they stand at
the moment of the transition. That reference and no other, because it is the only one that exists
when the transition happens: a per-row *retired at commit X* stamp would be a provenance label
naming a commit whose content it does not describe (196 M3), and it would be regenerated by the
same act that is doing the absorbing. Everything already recorded is not newly retired and does
not move.

⚑ **Q2 · Who notices, and when.** `--check` runs as `mutations:check`, gate step 5, and its `new`
rail already refuses a row that went stale since `CENSUS.md`. That rail could not fire, because the
documented order of work is *regenerate, then gate* — so the regeneration destroys the reference a
moment before the check reads it. The surface that sees the transition is therefore the
REGENERATION, and that is where this refuses. What it tells the reader to do is written out in
`retirement_refusal()`: open the path, decide whether the subject moved or died, correct the anchor
BY HAND and re-verify that row RED, or name the retirement back to this tool. `--check` keeps its
rail unchanged for the case where nobody regenerated at all.

⚑ **Q3 · The two ways a row goes dark — it can tell three shapes apart and NOT the one that
matters.** `file-gone`, `anchor-absent` and `anchor-ambiguous` are exact and mechanical. Whether an
absent anchor means *the text moved and the subject is alive* (`523 M15`, repairable) or *the
subject was deleted* (genuinely retired) is **not decidable here**, and nothing printed below claims
it is. That is why the refusal asks a person to look and why it will not re-anchor anything: a
correction is free and leaves the row holding a verdict measured against text that no longer exists.

⚑ **Q4 · The shape to follow.** `no row was re-run` is a claim the summary sentence makes because a
recorded artefact had to match a live one. Retirement now works the same way: the reason a row is
dark is recorded per row, `--check` compares it like every other attested field, and the summary
sentence says so rather than printing a bare count.

⚑ **Q5 · What the attestation needed.** It carried the retired ids and nothing to compare against.
It now carries, per table, `retirements` — the id mapped to the closed-vocabulary reason measured at
generation — and `census.py` writes it, so a reason that CHANGES (an absent anchor whose file then
leaves the tree) is a difference `--check` refuses to bless on its own.

USAGE
    python3 scripts/mutations/census.py            # write CENSUS.md
    python3 scripts/mutations/census.py --check    # fail if a row went stale or has a no-op edit
    python3 scripts/mutations/census.py \
        --retire "523 M15:anchor-absent"           # record a retirement you have looked at

The runner also owns one deliberately narrow internal command, `--begin-active-mutation`. It is
accepted only while that process owns the repository mutation lock. See the active-epoch contract
below; this is not a general way to ask the census to ignore working-tree bytes.
"""

