def _process_start(pid: int) -> str:
    try:
        result = subprocess.run(
            ["ps", "-o", "lstart=", "-p", str(pid)],
            capture_output=True,
            text=True,
            check=True,
        )
    except (OSError, subprocess.CalledProcessError) as error:
        raise ValueError(f"cannot read process start identity for pid {pid}: {error}") from error
    start = " ".join(result.stdout.split())
    if not start:
        raise ValueError(f"process start identity for pid {pid} is empty")
    return start


def _lock_owner() -> dict:
    owner = _mutation_lock() / "owner"
    if owner.is_symlink() or not owner.is_file():
        raise ValueError("tree lock owner is missing or not a regular file")
    try:
        text = owner.read_text().strip()
    except OSError as error:
        raise ValueError(f"tree lock owner is unreadable: {error}") from error
    match = re.fullmatch(
        r"pid ([1-9][0-9]*) · ([1-9][0-9]*) · process-start (.+) · "
        r"token ([0-9a-f]{32}) · ([^·]+)",
        text,
    )
    if not match:
        raise ValueError(f"tree lock owner is malformed: {text!r}")
    pid = int(match.group(1))
    table = match.group(2)
    recorded_start = " ".join(match.group(3).split())
    token = match.group(4)
    try:
        os.kill(pid, 0)
    except ProcessLookupError as error:
        raise ValueError(f"tree lock owner pid {pid} is not alive") from error
    except PermissionError:
        pass
    live_start = _process_start(pid)
    if recorded_start != live_start:
        raise ValueError(f"tree lock owner pid {pid} was reused by another process")
    return {"pid": pid, "table": table, "processStart": live_start, "token": token}


def _active_mutation_view(record: dict) -> dict[pathlib.Path, pathlib.Path]:
    """Validate a lock-owned declared mutation and return its pristine source projection."""

    if record.get("schema") != 1:
        raise ValueError("active mutation record has an unsupported schema")
    owner = _lock_owner()
    if record.get("ownerPid") != owner["pid"]:
        raise ValueError(
            f"active mutation owner {record.get('ownerPid')!r} does not match tree lock "
            f"{owner['pid']}"
        )
    table_id = record.get("table")
    if not isinstance(table_id, str) or not re.fullmatch(r"[1-9][0-9]*", table_id):
        raise ValueError(f"active mutation table is invalid: {table_id!r}")
    if owner["table"] != table_id or record.get("ownerTable") != owner["table"]:
        raise ValueError("active mutation table does not match the tree lock owner")
    if record.get("ownerProcessStart") != owner["processStart"]:
        raise ValueError("active mutation process-start identity does not match the tree lock")
    if record.get("lockToken") != owner["token"]:
        raise ValueError("active mutation token does not match the tree lock")
    index = record.get("index")
    if not isinstance(index, int) or index < 0:
        raise ValueError(f"active mutation index is invalid: {index!r}")

    pristine_value = record.get("pristineRoot")
    if not isinstance(pristine_value, str) or not pristine_value:
        raise ValueError("active mutation pristine root is missing")
    pristine = pathlib.Path(pristine_value).resolve()
    if not pristine.is_dir():
        raise ValueError(f"active mutation pristine root is not a directory: {pristine}")
    try:
        pristine.relative_to(REPO.resolve())
    except ValueError:
        pass
    else:
        raise ValueError("active mutation pristine root must be outside the repository")

    table = REPO / "scripts/mutations" / table_id / "mutations.py"
    rows = load(table)
    if index >= len(rows):
        raise ValueError(f"active mutation index {index} is outside table {table_id}")
    row = rows[index]
    identity = row_id(str(row[0]))
    fingerprint = row_fingerprint(table_id, row)
    if record.get("rowId") != identity:
        raise ValueError(
            f"active mutation row id {record.get('rowId')!r} does not match {identity}"
        )
    if record.get("definitionFingerprint") != fingerprint:
        raise ValueError("active mutation definition fingerprint is stale")

    protected = _protected_authority_paths()
    expected: dict[str, str] = {}
    pristine_paths: dict[str, pathlib.Path] = {}
    for rel_value, old, new in edits_of(row):
        rel = _safe_relative_path(str(rel_value)).as_posix()
        live_path = REPO / pathlib.Path(rel)
        if live_path.resolve() in protected or is_protected_authority(REPO, live_path):
            raise ValueError(f"the census cannot attest a mutation of its own authority: {rel}")
        if old == new:
            raise ValueError(f"active mutation {table_id}:{identity} contains an identical edit")
        if rel not in expected:
            pristine_path = pristine / pathlib.Path(rel)
            if pristine_path.is_symlink() or not pristine_path.is_file():
                raise ValueError(f"active mutation pristine file is missing or not regular: {rel}")
            try:
                pristine_path.resolve().relative_to(pristine)
            except ValueError as error:
                raise ValueError(f"active mutation pristine file escapes its root: {rel}") from error
            pristine_paths[rel] = pristine_path
            expected[rel] = pristine_path.read_text()
        if expected[rel].count(old) != 1:
            raise ValueError(
                f"active mutation {table_id}:{identity} pristine anchor count is not one in {rel}"
            )
        expected[rel] = expected[rel].replace(old, new, 1)

    recorded_files = record.get("files")
    if not isinstance(recorded_files, list):
        raise ValueError("active mutation file proof is missing")
    actual_files = []
    view = {}
    for rel in sorted(expected):
        live = REPO / pathlib.Path(rel)
        if live.is_symlink() or not live.is_file():
            raise ValueError(f"active mutation live target is missing or not regular: {rel}")
        try:
            live.resolve().relative_to(REPO.resolve())
        except ValueError as error:
            raise ValueError(f"active mutation live target escapes the repository: {rel}") from error
        live_text = live.read_text()
        if live_text != expected[rel]:
            raise ValueError(
                f"live target is not exactly declared mutation {table_id}:{identity}: {rel}"
            )
        actual_files.append(
            {
                "path": rel,
                "pristineSha256": hashlib.sha256(pristine_paths[rel].read_bytes()).hexdigest(),
                "mutatedSha256": hashlib.sha256(live.read_bytes()).hexdigest(),
            }
        )
        view[live.resolve()] = pristine_paths[rel]
    if recorded_files != actual_files:
        raise ValueError("active mutation file proof does not match the live/pristine bytes")
    return view


def begin_active_mutation(
    table_id: str,
    index_text: str,
    pristine_root: str,
    owner_text: str,
    definition_path: str | None = None,
) -> None:
    """Create the fail-closed epoch consumed by `--check` while one declared row is active."""

    try:
        index = int(index_text)
        owner_pid = int(owner_text)
    except ValueError as error:
        raise ValueError("active mutation index and owner pid must be integers") from error
    owner = _lock_owner()
    if owner_pid != owner["pid"]:
        raise ValueError("active mutation caller does not own the repository tree lock")
    epoch = _active_mutation_path()
    if epoch.exists() or epoch.is_symlink():
        raise ValueError(f"an active mutation epoch already exists: {epoch}")

    if not re.fullmatch(r"[1-9][0-9]*", table_id):
        raise ValueError(f"active mutation table is invalid: {table_id!r}")
    if owner["table"] != table_id:
        raise ValueError("active mutation table does not match the repository tree lock")
    table = REPO / "scripts/mutations" / table_id / "mutations.py"
    definition = pathlib.Path(definition_path) if definition_path is not None else table
    rows = load(definition)
    if index < 0 or index >= len(rows):
        raise ValueError(f"active mutation index {index} is outside table {table_id}")
    row = rows[index]
    pristine = pathlib.Path(pristine_root).resolve()
    files = []
    seen = set()
    for rel_value, _old, _new in edits_of(row):
        rel = _safe_relative_path(str(rel_value)).as_posix()
        if rel in seen:
            continue
        seen.add(rel)
        pristine_path = pristine / pathlib.Path(rel)
        live_path = REPO / pathlib.Path(rel)
        if not pristine_path.is_file() or not live_path.is_file():
            raise ValueError(f"active mutation target or pristine copy is missing: {rel}")
        files.append(
            {
                "path": rel,
                "pristineSha256": hashlib.sha256(pristine_path.read_bytes()).hexdigest(),
                "mutatedSha256": hashlib.sha256(live_path.read_bytes()).hexdigest(),
            }
        )
    record = {
        "schema": 1,
        "ownerPid": owner_pid,
        "ownerTable": owner["table"],
        "ownerProcessStart": owner["processStart"],
        "lockToken": owner["token"],
        "table": table_id,
        "index": index,
        "rowId": row_id(str(row[0])),
        "definitionFingerprint": row_fingerprint(table_id, row),
        "pristineRoot": str(pristine),
        "files": sorted(files, key=lambda item: item["path"]),
    }
    _active_mutation_view(record)
    temporary = epoch.with_name(f".{ACTIVE_MUTATION_RECORD}.{os.getpid()}.tmp")
    temporary.write_text(json.dumps(record, indent=2, sort_keys=True) + "\n")
    os.replace(temporary, epoch)


def configure_active_mutation_view() -> None:
    """Enable the verified view for a check spawned inside an active mutation row."""

    global _ACTIVE_LIVE_SHA256, _ACTIVE_MUTATION, _ACTIVE_SOURCE_VIEW
    # Validation must never inherit a projection left by an earlier call in the same Python
    # process. The CLI is one-shot, but keeping this function self-contained is what makes its
    # adversarial fixture trustworthy too.
    _ACTIVE_SOURCE_VIEW = {}
    _ACTIVE_LIVE_SHA256 = {}
    _ACTIVE_MUTATION = None
    epoch = _active_mutation_path()
    if not epoch.exists() and not epoch.is_symlink():
        return
    if epoch.is_symlink() or not epoch.is_file():
        raise ValueError("active mutation record is not a regular file")
    try:
        record = json.loads(epoch.read_text())
    except (OSError, json.JSONDecodeError) as error:
        raise ValueError(f"active mutation record is unreadable: {error}") from error
    if not isinstance(record, dict):
        raise ValueError("active mutation record is not an object")
    view = _active_mutation_view(record)
    _ACTIVE_SOURCE_VIEW = view
    _ACTIVE_LIVE_SHA256 = {
        (REPO / item["path"]).resolve(): item["mutatedSha256"] for item in record["files"]
    }
    _ACTIVE_MUTATION = record


def assert_active_mutation_unchanged() -> None:
    """Revalidate owner and bytes at the far side of a census check."""

    if _ACTIVE_MUTATION is not None:
        _active_mutation_view(_ACTIVE_MUTATION)


def _result_body(lines: list[str], start: int) -> list[str]:
    """Only the immediate contiguous indented record belongs to a row/control header."""

    body = []
    for line in lines[start + 1 :]:
        if not line.strip():
            break
        if not line[:1].isspace():
            break
        body.append(line)
    return body


def _parse_results(
    body: list[str],
    baseline: dict[str, int],
    *,
    require_all_projects: bool,
    allow_not_run: bool = False,
    allow_legacy_alias: bool = True,
    not_run_error: str | None = None,
) -> tuple[dict[str, str], dict[str, str], set[str], list[str]]:
    """Parse every result cell, with the sole legacy alias made explicit.

    Tables 151/154 predate project-labelled node cells.  Their `node:` cell is accepted only when
    its total selects exactly one otherwise-missing baseline project.  A generic equal-count GREEN
    is never allowed to satisfy two projects.
    """

    if not body:
        return {}, {}, set(), ["result record is absent"]
    cells = [
        cell.strip()
        for line in body
        for cell in re.split(r"\s+(?:·|\|)\s+", line.strip())
        if cell.strip()
    ]
    projects: dict[str, str] = {}
    channels: dict[str, str] = {}
    not_run: set[str] = set()
    aliases: list[tuple[str, int, int]] = []
    errors = []
    for cell in cells:
        omitted = NOT_RUN_RESULT.fullmatch(cell)
        if omitted:
            project = omitted.group(1)
            if project in projects or project in not_run:
                errors.append(f"duplicate {project} result")
                continue
            not_run.add(project)
            if not allow_not_run:
                errors.append(
                    not_run_error
                    or f"{project} {NOT_RUN_LITERAL} requires a v1 declaration"
                )
            if project not in baseline:
                errors.append(f"unexpected project result: {project}")
            continue

        normal = NORMAL_RESULT.fullmatch(cell)
        if normal:
            node_prefix, project, verdict, failures, total, _files = normal.groups()
            failures_int, total_int = int(failures), int(total)
            if verdict == "GREEN" and failures_int != 0:
                errors.append(f"malformed GREEN cell: {cell}")
            if verdict == "RED" and failures_int == 0:
                errors.append(f"malformed RED cell: {cell}")
            if project is None:
                if node_prefix is None:
                    errors.append(f"unlabelled result cell: {cell}")
                elif not allow_legacy_alias:
                    errors.append(f"legacy node result is forbidden by v1: {cell}")
                else:
                    aliases.append((verdict, failures_int, total_int))
                continue
            if project in projects or project in not_run:
                errors.append(f"duplicate {project} result")
                continue
            projects[project] = verdict
            if project not in baseline:
                errors.append(f"unexpected project result: {project}")
            elif total_int != baseline[project]:
                errors.append(
                    f"{project} collected {total_int} of baseline {baseline[project]}"
                )
            continue

        adverse = ADVERSE_RESULT.fullmatch(cell)
        if adverse:
            project, verdict = adverse.groups()
            if project in projects or project in not_run:
                errors.append(f"duplicate {project} result")
            else:
                projects[project] = verdict
            if project not in baseline:
                errors.append(f"unexpected project result: {project}")
            continue

        channel = CHANNEL_RESULT.fullmatch(cell)
        if channel:
            name, verdict = channel.groups()
            if name in channels:
                errors.append(f"duplicate {name} result")
            channels[name] = verdict
            continue
        errors.append(f"unparseable result cell: {cell}")

    for verdict, _failures, total in aliases:
        candidates = [
            project
            for project, expected in baseline.items()
            if project not in projects and project not in not_run and expected == total
        ]
        if len(candidates) != 1:
            errors.append(f"legacy node result with total {total} is ambiguous")
            continue
        projects[candidates[0]] = verdict

    satisfied = set(projects) | (not_run if allow_not_run else set())
    missing = sorted(set(baseline) - satisfied)
    if require_all_projects and missing:
        errors.append(f"missing project result(s): {', '.join(missing)}")
    return projects, channels, not_run, errors


def _reachability_snapshot(
    lines: list[str], m0_index: int | None
) -> tuple[dict[str, str] | None, list[str]]:
    """Parse the prospective v1 route declaration without changing legacy artefacts.

    The topology digest identifies the frozen v1 map in `lib/reachability.py`, not today's source
    graph. Consequently a historical v1 artefact is always checked against the map it declared and
    is never silently reinterpreted after product imports change. `unproved` is the explicit
    fail-closed snapshot: every baseline project must have been measured.
    """

    candidates = [
        (index, line)
        for index, line in enumerate(lines)
        if line.strip().startswith(REACHABILITY_PREFIX)
    ]
    if not candidates:
        return None, []
    if len(candidates) != 1:
        return None, [
            f"expected one project-reachability declaration, found {len(candidates)}"
        ]

    index, raw = candidates[0]
    if raw != raw.strip():
        return None, ["project-reachability declaration is not an exact top-level line"]
    match = REACHABILITY_DECLARATION.fullmatch(raw)
    if not match:
        return None, ["project-reachability declaration is malformed or unsupported"]
    version, topology = match.groups()
    if version != POLICY_VERSION:
        return None, [f"unsupported project-reachability policy: {version}"]
    if topology not in {"unproved", TOPOLOGY_SHA256}:
        return None, [f"unknown {version} topology snapshot: {topology}"]
    errors = []
    if m0_index is None:
        errors.append("project-reachability declaration cannot precede a missing M0")
    elif index >= m0_index:
        errors.append("project-reachability declaration does not precede M0")
    return {"policy": version, "topology": topology}, errors


def _row_scope_snapshot(
    lines: list[str], m0_index: int | None
) -> tuple[dict[int, tuple[str, int, tuple[str, ...]]] | None, list[str]]:
    """The killer groups an artefact declares before M0 — or `None` for one that ran none (W4.36)."""

    declared = [index for index, line in enumerate(lines) if line == ROW_SCOPE_DECLARATION]
    group_lines = [
        (index, line) for index, line in enumerate(lines) if line.startswith("# killer-group ")
    ]
    if not declared and not group_lines:
        return None, []
    errors = []
    if len(declared) != 1:
        errors.append(f"expected one row-scope declaration, found {len(declared)}")
    groups: dict[int, tuple[str, int, tuple[str, ...]]] = {}
    for index, line in group_lines:
        match = KILLER_GROUP_LINE.fullmatch(line)
        if match is None:
            errors.append(f"malformed killer group: {line}")
            continue
        number, project, total, files = match.groups()
        if int(number) in groups:
            errors.append(f"duplicate killer group G{number}")
            continue
        if int(total) == 0:
            errors.append(f"killer group G{number} has zero tests")
        if m0_index is None or index >= m0_index:
            errors.append(f"killer group G{number} does not precede M0")
        groups[int(number)] = (project, int(total), tuple(files.split(" ")))
    if not groups:
        errors.append("a row-scope declaration with no killer group")
    if sorted(groups) != list(range(1, len(groups) + 1)):
        errors.append("killer groups are not numbered G1..Gn")
    return groups, errors


def _parse_killer_line(
    line: str, groups: dict[int, tuple[str, int, tuple[str, ...]]]
) -> tuple[dict[int, str], list[str]]:
    """One `killers:` record: each named group's verdict, its total checked against its baseline."""

    errors = []
    verdicts: dict[int, str] = {}
    text = line.strip()[len(KILLERS_PREFIX) :].strip()
    for cell in (part.strip() for part in re.split(r"\s+·\s+", text) if part.strip()):
        normal = KILLER_RESULT.fullmatch(cell)
        adverse = KILLER_ADVERSE.fullmatch(cell)
        if normal is None and adverse is None:
            errors.append(f"unparseable killer cell: {cell}")
            continue
        number = int((normal or adverse).group(1))
        if number not in groups:
            errors.append(f"killer cell names an undeclared group: G{number}")
            continue
        if number in verdicts:
            errors.append(f"duplicate G{number} result")
            continue
        if normal is not None:
            _number, verdict, failures, total, _files = normal.groups()
            if verdict == "GREEN" and int(failures) != 0:
                errors.append(f"malformed GREEN cell: {cell}")
            if verdict == "RED" and int(failures) == 0:
                errors.append(f"malformed RED cell: {cell}")
            if int(total) != groups[number][1]:
                errors.append(f"G{number} collected {total} of baseline {groups[number][1]}")
            verdicts[number] = verdict
        else:
            verdicts[number] = adverse.group(2)
    if not verdicts and not errors:
        errors.append("a killers record with no group")
    return verdicts, errors


def _split_killer_lines(body: list[str]) -> tuple[list[str], list[str]]:
    killer_lines = [line for line in body if line.strip().startswith(KILLERS_PREFIX)]
    return [line for line in body if line not in killer_lines], killer_lines


def _baseline_from_header(header: str) -> tuple[dict[str, int], list[str]]:
    if "baseline " not in header:
        return {}, ["M0 has no baseline inventory"]
    inventory = header.split("baseline ", 1)[1].strip()
    pair_pattern = rf"({PROJECT_PATTERN})=([0-9]+)"
    if not re.fullmatch(rf"{pair_pattern}(?:\s+{pair_pattern})*", inventory):
        return {}, ["M0 baseline inventory is not structurally valid"]
    pairs = re.findall(pair_pattern, inventory)
    names = [project for project, _total in pairs]
    errors = []
    if len(names) != len(set(names)):
        errors.append("M0 baseline inventory repeats a project")
    baseline = {project: int(total) for project, total in pairs}
    zero = sorted(project for project, total in baseline.items() if total == 0)
    if zero:
        errors.append(f"M0 baseline has zero tests for: {', '.join(zero)}")
    return baseline, errors


def _control_killer_errors(
    killer_lines: list[str], groups: dict[int, tuple[str, int, tuple[str, ...]]] | None
) -> list[str]:
    """A control runs every declared killer group, once, and every one of them GREEN."""

    if groups is None:
        return ["has a killers record but the artefact declares no killer group"] if killer_lines else []
    if len(killer_lines) != 1:
        return [f"expected one killers record over every group, found {len(killer_lines)}"]
    verdicts, errors = _parse_killer_line(killer_lines[0], groups)
    missing = sorted(set(groups) - set(verdicts))
    if missing:
        errors.append("killer group(s) not run: " + ", ".join(f"G{number}" for number in missing))
    adverse = sorted(f"G{number}={verdict}" for number, verdict in verdicts.items() if verdict != "GREEN")
    if adverse:
        errors.append(f"killer groups are not healthy ({', '.join(adverse)})")
    return errors


def run_attestation(
    table: pathlib.Path, definition_rows: list[dict], retirements: dict[str, dict]
) -> dict:
    """Strictly parse one runner artefact without re-evaluating any historical verdict.

    ⚑ **596 · the third number.** Since the runner can DECLINE a row the census records as
    retired, *how many rows this table has* and *how many it took a verdict on* are no longer the
    same number, and a reader that conflates them claims coverage the run does not have. A
    declined row still writes its header — so the roster and the label order still have to match
    the definition exactly — and its body is the one line `table_contract.retired_row_record`
    renders. It is accepted only when the census records THAT row retired for THAT reason right
    now; a RETIRED line for anything else is an invalid row, and a real verdict for a row that has
    since retired is left exactly as it was, because it was taken when the anchor was alive.
    """

    artifact = table / "mutations.txt"
    if not artifact.exists():
        return {
            "state": "unrun",
            "artifact": None,
            "artifactRows": 0,
            "artifactSha256": None,
            "invalidRows": [],
            "rowVerdicts": [],
            "reasons": ["mutations.txt is absent"],
        }

    artifact_bytes = artifact.read_bytes()
    lines = artifact_bytes.decode(errors="replace").splitlines()
    m0_indexes = [i for i, line in enumerate(lines) if line.startswith("M0 ")]
    mend_indexes = [i for i, line in enumerate(lines) if line.startswith("M-END ")]
    reasons = []
    if len(m0_indexes) != 1:
        reasons.append(f"expected one M0 control, found {len(m0_indexes)}")
    if len(mend_indexes) != 1:
        reasons.append(f"expected one M-END control, found {len(mend_indexes)}")
    m0_index = m0_indexes[0] if len(m0_indexes) == 1 else None
    mend_index = mend_indexes[0] if len(mend_indexes) == 1 else None
    reachability, reachability_errors = _reachability_snapshot(lines, m0_index)
    reasons.extend(reachability_errors)
    baseline, baseline_errors = (
        _baseline_from_header(lines[m0_index]) if m0_index is not None else ({}, [])
    )
    reasons.extend(baseline_errors)
    killer_groups, row_scope_errors = _row_scope_snapshot(lines, m0_index)
    reasons.extend(row_scope_errors)

    headers: list[tuple[int, str, str]] = []
    for index, line in enumerate(lines):
        match = ROW_HEADER.match(line)
        if match:
            headers.append((index, match.group(1), line.strip()))
    canonical_rows = [row["id"] for row in definition_rows]
    artifact_rows = [identity for _index, identity, _label in headers]
    if len(artifact_rows) != len(set(artifact_rows)):
        duplicate = sorted(
            identity for identity in set(artifact_rows) if artifact_rows.count(identity) > 1
        )
        reasons.append(f"duplicate row verdicts: {', '.join(duplicate)}")
    missing = sorted(set(canonical_rows) - set(artifact_rows))
    extra = sorted(set(artifact_rows) - set(canonical_rows))
    if missing:
        reasons.append(f"missing row verdicts: {', '.join(missing)}")
    if extra:
        reasons.append(f"unknown row verdicts: {', '.join(extra)}")
    if len(artifact_rows) != len(canonical_rows):
        reasons.append(
            f"artifact has {len(artifact_rows)} row record(s), definition has {len(canonical_rows)}"
        )
    expected_labels = [row["label"] for row in definition_rows]
    actual_labels = [label for _index, _identity, label in headers]
    if actual_labels != expected_labels:
        reasons.append("artifact row labels/order do not match the current definition roster")
    if m0_index is not None and headers and m0_index >= headers[0][0]:
        reasons.append("M0 does not precede every mutation row")
    if mend_index is not None and headers and mend_index <= headers[-1][0]:
        reasons.append("M-END does not follow every mutation row")

    control_channels: set[str] = set()
    if m0_index is not None:
        control_body, control_killers = _split_killer_lines(_result_body(lines, m0_index))
        reasons.extend(f"M0 {error}" for error in _control_killer_errors(control_killers, killer_groups))
        projects, channels, _not_run, errors = _parse_results(
            control_body,
            baseline,
            require_all_projects=True,
            allow_legacy_alias=reachability is None,
            not_run_error="control results must be measured; NOT RUN is forbidden",
        )
        reasons.extend(f"M0 {error}" for error in errors)
        adverse = sorted(
            [f"{name}={verdict}" for name, verdict in {**projects, **channels}.items() if verdict != "GREEN"]
        )
        if adverse:
            reasons.append(f"M0 is not healthy ({', '.join(adverse)})")
        control_channels = set(channels)
    if mend_index is not None:
        control_body, control_killers = _split_killer_lines(_result_body(lines, mend_index))
        reasons.extend(f"M-END {error}" for error in _control_killer_errors(control_killers, killer_groups))
        projects, channels, _not_run, errors = _parse_results(
            control_body,
            baseline,
            require_all_projects=True,
            allow_legacy_alias=reachability is None,
            not_run_error="control results must be measured; NOT RUN is forbidden",
        )
        reasons.extend(f"M-END {error}" for error in errors)
        adverse = sorted(
            [f"{name}={verdict}" for name, verdict in {**projects, **channels}.items() if verdict != "GREEN"]
        )
        if adverse:
            reasons.append(f"M-END is not healthy ({', '.join(adverse)})")
        if set(channels) != control_channels:
            reasons.append("M0 and M-END product-channel rosters differ")

    invalid_rows = []
    row_verdicts = []
    retired_skipped: list[str] = []
    definitions_by_id = {row["id"]: row for row in definition_rows}
    for start, identity, _label in headers:
        body = _result_body(lines, start)
        stripped = [line.strip() for line in body]
        if any(line.startswith(RETIRED_ROW_PREFIX) for line in stripped):
            recorded = retirements.get(identity)
            expected = (
                retired_row_record(recorded["reason"]) if recorded is not None else None
            )
            if expected is not None and stripped == [expected]:
                retired_skipped.append(identity)
                continue
            invalid_rows.append(identity)
            reasons.append(
                f"{identity} declines to run but the census does not record it retired that way"
            )
            continue
        row_body, row_killer_lines = _split_killer_lines(body)
        if row_killer_lines:
            # ⚑ W4.36 · a row measured by its killers: its record is the one `killers:` line, and the
            # groups it names are exactly its label's killers, grouped by project, as they resolve now.
            killer_errors = []
            group_verdicts: dict[int, str] = {}
            if killer_groups is None:
                killer_errors.append("has a killers record but the artefact declares no killer group")
            elif row_body or len(row_killer_lines) != 1:
                killer_errors.append("a killers record must be the row's whole record")
            else:
                group_verdicts, killer_errors = _parse_killer_line(row_killer_lines[0], killer_groups)
                definition = definitions_by_id.get(identity)
                resolved, why = row_killers(REPO, definition["label"]) if definition else ([], "no definition")
                if why is not None:
                    killer_errors.append(f"its killers no longer resolve: {why}")
                else:
                    wanted = set(groups_of(resolved))
                    named = {
                        (killer_groups[number][0], killer_groups[number][2])
                        for number in group_verdicts
                    }
                    if named != wanted:
                        killer_errors.append("the killer groups it ran are not its label's killers")
            adverse = sorted(
                f"G{number}={verdict}"
                for number, verdict in group_verdicts.items()
                if verdict in INVALID_VERDICTS
            )
            if killer_errors or adverse:
                invalid_rows.append(identity)
                detail = killer_errors + ([f"non-evidentiary: {', '.join(adverse)}"] if adverse else [])
                reasons.append(f"{identity} " + "; ".join(detail))
            else:
                aggregate = "RED" if "RED" in group_verdicts.values() else "GREEN"
                row_verdicts.append(
                    {
                        "id": f"{table.name}:{identity}",
                        "verdict": aggregate,
                        "killerGroupVerdicts": {
                            f"G{number}": group_verdicts[number] for number in sorted(group_verdicts)
                        },
                    }
                )
            continue
        projects, channels, not_run, errors = _parse_results(
            body,
            baseline,
            require_all_projects=reachability is not None,
            allow_not_run=reachability is not None,
            allow_legacy_alias=reachability is None,
        )
        if reachability is not None:
            definition = definitions_by_id.get(identity)
            edit_paths = definition.get("editPaths") if definition is not None else None
            if (
                not isinstance(edit_paths, list)
                or not edit_paths
                or not all(isinstance(path, str) and path for path in edit_paths)
            ):
                errors.append("v1 route has no valid definition edit-path snapshot")
            else:
                topology_proved = reachability["topology"] != "unproved"
                derived = set(derive_projects(edit_paths, topology_proved=topology_proved))
                expected_not_run = {
                    project
                    for project in baseline
                    if project in REACHABILITY_PROJECTS and project not in derived
                }
                unexpected_omissions = sorted(not_run - expected_not_run)
                if unexpected_omissions:
                    errors.append(
                        "reachable project(s) marked NOT RUN: "
                        + ", ".join(unexpected_omissions)
                    )
                # A runtime helper may fail closed from the proved route to ALL. Extra measured
                # GREEN projects are a safe superset and remain real evidence. An out-of-reach RED
                # cannot be attributed to this row, however: counting it would manufacture a kill
                # from a project the frozen graph says the edit cannot reach.
                out_of_reach_red = sorted(
                    project
                    for project in expected_not_run
                    if projects.get(project) == "RED"
                )
                if out_of_reach_red:
                    errors.append(
                        "out-of-reach project(s) measured RED: "
                        + ", ".join(out_of_reach_red)
                    )
            if baseline and not projects and not channels:
                errors.append("all baseline projects are NOT RUN")
        elif not projects and not channels:
            errors.append("result record has no project or product-channel verdict")
        if set(channels) != control_channels:
            errors.append("product-channel roster differs from controls")
        outcomes = {**projects, **channels}
        adverse = sorted(
            f"{name}={verdict}"
            for name, verdict in outcomes.items()
            if verdict in INVALID_VERDICTS or verdict in ADVERSE_MARKERS
        )
        if any("DID NOT APPLY" in line for line in body):
            adverse.append("DID NOT APPLY")
        if errors or adverse:
            invalid_rows.append(identity)
            detail = errors + ([f"non-evidentiary: {', '.join(adverse)}"] if adverse else [])
            reasons.append(f"{identity} " + "; ".join(detail))
        else:
            aggregate = "RED" if "RED" in outcomes.values() else "GREEN"
            verdict = {"id": f"{table.name}:{identity}", "verdict": aggregate}
            if reachability is not None:
                verdict["projectVerdicts"] = {
                    project: projects[project] for project in baseline if project in projects
                }
                verdict["notRunProjects"] = [
                    project for project in baseline if project in not_run
                ]
            row_verdicts.append(verdict)

    state = "complete" if not reasons else "partial-or-invalid"
    result = {
        "state": state,
        "artifact": str(artifact.relative_to(REPO)),
        "artifactRows": len(artifact_rows),
        "artifactSha256": hashlib.sha256(artifact_bytes).hexdigest(),
        "invalidRows": sorted(set(invalid_rows)),
        "rowVerdicts": row_verdicts,
        "reasons": reasons,
    }
    # ⛔ 596 · the key appears only when a run actually declined something, so an artefact written
    # before this existed attests byte-for-byte what it attested before. `artifactRows` still
    # counts every header; `retiredSkipped` is how many of them carry no verdict, and the
    # difference is the coverage this run has.
    if retired_skipped:
        result["retiredSkipped"] = sorted(set(retired_skipped))
    if reachability is not None:
        result["projectReachability"] = reachability
    if killer_groups:
        result["killerGroups"] = {
            f"G{number}": {"project": project, "tests": total, "files": list(files)}
            for number, (project, total, files) in sorted(killer_groups.items())
        }
    return result


def census():
    tables = sorted(
        table
        for table in HERE.iterdir()
        if not table.is_symlink()
        and table.is_dir()
        and not (table / "mutations.py").is_symlink()
        and (table / "mutations.py").is_file()
    )
    out = []
    for table in tables:
        rows = load(table / "mutations.py")
        stale, unchanged, touched = [], [], {}
        retirements: dict[str, dict] = {}
        canonical_rows = [row_id(str(row[0])) for row in rows]
        duplicates = sorted(
            identity for identity in set(canonical_rows) if canonical_rows.count(identity) > 1
        )
        if duplicates:
            raise ValueError(f"table {table.name} repeats canonical ids: {', '.join(duplicates)}")
        fingerprints = [row_fingerprint(table.name, row) for row in rows]
        definition_rows = [
            {
                "id": identity,
                "canonicalId": f"{table.name}:{identity}",
                "label": str(row[0]).strip(),
                "fingerprint": fingerprint,
                "editPaths": list(dict.fromkeys(str(edit[0]) for edit in edits_of(row))),
            }
            for identity, row, fingerprint in zip(canonical_rows, rows, fingerprints)
        ]
        # ⛔ 528: `!= 1` was one branch and is two facts. An anchor nothing matches and an anchor
        # that matches twice are different accidents with different repairs, and the census
        # recorded neither. Both still retire the row; only the word differs.
        # ⚑ 596: the branch above is now `table_contract.darkness`, so the runner decides which
        # rows it may decline with THIS derivation rather than one of its own. What stays here is
        # the part only the census does: the per-path hash inventory, and reading a proved pristine
        # projection rather than the live bytes while a mutation epoch is active.
        def read_for_census(rel: str) -> str | None:
            path = source_view(REPO / rel)
            if not path.exists():
                touched.setdefault(rel, "(file no longer in the tree)")
                return None
            text = path.read_text()
            touched.setdefault(rel, hashlib.sha256(text.encode()).hexdigest()[:16])
            return text

        for row in rows:
            edits = edits_of(row)
            if any(old == new for (_rel, old, new) in edits):
                unchanged.append(row_id(row[0]))
            reason, dark_paths = darkness(edits, read_for_census)
            if reason is not None:
                identity = row_id(row[0])
                stale.append(identity)
                retirements[identity] = {
                    "reason": reason,
                    "paths": dark_paths,
                    "label": str(row[0]).strip(),
                }
        out.append(
            {
                "table": table.name,
                "rows": len(rows),
                "stale": stale,
                "retirements": retirements,
                "unchanged": unchanged,
                "files": touched,
                "canonicalRows": canonical_rows,
                "definitionRows": definition_rows,
                "definitionFingerprint": hashlib.sha256("\n".join(fingerprints).encode()).hexdigest(),
                "run": run_attestation(table, definition_rows, retirements),
            }
        )
    return out


def head() -> str:
    """The commit the census describes — and whether the tree it read was that commit.

    ⛔ 196 M3: this said `f458f23` on a report generated from a working tree that already contained
    table 188, which does not exist at that commit — all 148 stored hashes matched the LATER commit.
    The stamp named the parent and the content described the child, which is the one thing a
    provenance label may not do. `mutate.sh` has said `HEAD … + working tree` since 146; so does this.
    """
    try:
        commit = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=REPO, capture_output=True, text=True, check=True,
        ).stdout.strip()
    except Exception:
        return "unknown"
    try:
        dirty = subprocess.run(
            ["git", "status", "--porcelain"],
            cwd=REPO, capture_output=True, text=True, check=True,
        ).stdout.strip()
    except Exception:
        return commit
    return f"{commit} + working tree" if dirty else commit


def render(data, stamp: str) -> str:
    total = sum(entry["rows"] for entry in data)
    dead = sum(len(entry["stale"]) for entry in data)
    state_tables = {
        state: sum(entry["run"]["state"] == state for entry in data)
        for state in ("complete", "partial-or-invalid", "unrun")
    }
    state_rows = {
        state: sum(entry["rows"] for entry in data if entry["run"]["state"] == state)
        for state in state_tables
    }
    lines = [
        "# Mutation census",
        "",
        f"**Generated by `scripts/mutations/census.py` at `{stamp}`.** Regenerate with",
        "`pnpm run mutations:census`; `--check` validates this report and the machine-readable "
        "`ATTESTATION.json` beside it.",
        "",
        f"**{total} defined rows across {len(data)} tables. {dead} can no longer apply** "
        f"({total - dead} still can).",
        "",
        f"**Run state:** {state_rows['complete']} rows / {state_tables['complete']} tables complete · "
        f"{state_rows['partial-or-invalid']} rows / {state_tables['partial-or-invalid']} tables "
        f"partial-or-invalid · {state_rows['unrun']} rows / {state_tables['unrun']} tables unrun.",
        "",
        "A row that cannot apply is RETIRED IN PLACE: its definition stays in its table and any "
        "historical outcome stays in `mutations.txt`, but it protects nothing at this commit. "
        "⚑ **596: a run under the shared driver DECLINES it by name** — the artefact carries the "
        "row's header and `RETIRED · <reason> · not run` in place of a verdict, and its summary "
        "counts it apart from the rows that ran. Before that, one retired row refused the whole "
        "table at the dry-run gate. A grandfathered inline runner has no such gate and still "
        "reports the row as `DID NOT APPLY`. Nothing is deleted (142's rule).",
        "",
        "## ⛔ What this file attests, and what it does not (196 M3)",
        "",
        "⛔ **Run-state checks are structural, not re-runs.** `complete` means the versioned runner "
        "artefact strictly parsed with healthy `M0` and `M-END`, exactly one result record for "
        "every full canonical row id, and no `INVALID`, `ERROR`, `NO-REPORT`, `NO-TESTS` or "
        "`DID NOT APPLY`. ⚑ **596: a record may be a DECLINED row** — the driver writes one for a "
        "row this file already records as retired, and only for that exact reason — so `complete` "
        "means every row has an ACCOUNT, not that every row has a verdict. `retiredSkipped` in "
        "`ATTESTATION.json` names the declined ones, and the table below shows how many. "
        "`ATTESTATION.json` binds the parsed roster, row verdicts, per-row "
        "definition fingerprints and source artefact SHA-256 in a machine-readable record. "
        "It does **not** re-attest that an old RED is semantically valid; that still requires review "
        "or a re-run. `partial-or-invalid` names an artefact that cannot support the universal run "
        "claim, while `unrun` means no artefact exists.",
        "",
        "🔴 **A row containing identical old and new text is rejected by `--check`.** That edit "
        "matches its anchor and appears to apply, but changes no bytes. In a single-edit row every "
        "test then sees the pristine tree, creating a phantom survivor rather than mutation evidence; "
        "in a composite row it silently leaves part of the claimed defect untested.",
        "",
        "⚠️ **\"Recorded outcome\", not \"recorded RED.\"** An earlier version of this header said "
        "every row carries a recorded RED. It does not: `158 M6` and `188 M16` are recorded GREEN "
        "deliberately, each with its reason in its own `mutations.txt`, and a census that describes "
        "them as REDs is describing a table that does not exist.",
        "",
        "⚑ **Definition fingerprints are a gate; current-file hashes are provenance.** The "
        "definition fingerprint covers table, full canonical id, complete label, ordered paths, old "
        "anchors and replacements, so changing one nonidentical mutation into another fails "
        "`--check`. The file hashes farther below answer whether today's target bytes differ from "
        "the tree named by historical evidence; ordinary product edits do not fail on that alone.",
        "",
        "| table | defined | applicable | retired | run state | artefact rows | definition |",
        "|---|---:|---:|---:|---|---:|---|",
    ]
    for entry in data:
        live = entry["rows"] - len(entry["stale"])
        # ⚑ 596: `artefact rows` counts every record the run wrote, and some of them may be
        # declines rather than verdicts. The suffix appears only when a run actually declined
        # something, so a table nobody has run since this landed reads exactly as it did.
        declined = len(entry["run"].get("retiredSkipped", []))
        artefact_rows = f"{entry['run']['artifactRows']}"
        if declined:
            artefact_rows += f" · {declined} declined"
        lines.append(
            f"| {entry['table']} | {entry['rows']} | {live} | {len(entry['stale'])} | "
            f"{entry['run']['state']} | {artefact_rows} | "
            f"`{entry['definitionFingerprint'][:16]}` |"
        )
    lines += ["", "## Unrun and partial-or-invalid tables", ""]
    incomplete = [entry for entry in data if entry["run"]["state"] != "complete"]
    if not incomplete:
        lines.append("_None — every table has one structurally complete artefact._")
    for entry in incomplete:
        reasons = "; ".join(entry["run"]["reasons"])
        lines.append(f"- **{entry['table']} · {entry['run']['state']}** — {reasons}")
    lines += [
        "",
        "## Retired rows",
        "",
        "⛔ **528: each one carries the shape of its darkness, and none of them claims to know "
        "whether the subject moved or died.** `file-gone` is a declared path that is not in the "
        "tree; `anchor-absent` is a path that is, holding no copy of the anchor; "
        "`anchor-ambiguous` is a path holding more than one, so no single occurrence can be the "
        "one the row meant. A row with several failing edits carries every reason it produced. "
        "⚑ A row arriving in this list for the first time makes `census.py` REFUSE to write until "
        "somebody names it back — see `retirement_refusal()`.",
        "",
    ]
    if dead == 0:
        lines.append("_None — every defined row still applies at this commit._")
    for entry in data:
        for row in entry["stale"]:
            record = entry["retirements"][row]
            where = ", ".join(f"`{path}`" for path in record["paths"])
            lines.append(
                f"- {entry['table']} {row}{RETIREMENT_SEPARATOR}{record['reason']}"
                f"{RETIREMENT_SEPARATOR}{where}"
            )
    lines += [
        "",
        "## The files each table touches, and what they are now",
        "",
        "⚑ **168 L6 and 182 L5, answered together.** A `mutations.txt` records an outcome against a "
        "tree it names only by commit; these hashes let a reader tell whether the file a row "
        "mutated is still the file the row was run against.",
        "",
        "| table | file | sha256 (first 16) |",
        "|---|---|---|",
    ]
    for entry in data:
        for rel, digest in sorted(entry["files"].items()):
            lines.append(f"| {entry['table']} | `{rel}` | `{digest}` |")
    return "\n".join(lines) + "\n"


def attestation(data) -> dict:
    """The stable machine-readable state that CI compares; no commit stamp or prose."""

    states = ("complete", "partial-or-invalid", "unrun")
    return {
        "schema": 1,
        "summary": {
            "definedRows": sum(entry["rows"] for entry in data),
            "tables": len(data),
            "retiredRows": sum(len(entry["stale"]) for entry in data),
            "rowsByRunState": {
                state: sum(entry["rows"] for entry in data if entry["run"]["state"] == state)
                for state in states
            },
            "tablesByRunState": {
                state: sum(entry["run"]["state"] == state for entry in data)
                for state in states
            },
        },
        "tables": [
            {
                "table": entry["table"],
                "definedRows": entry["rows"],
                "canonicalRows": entry["canonicalRows"],
                "rows": [
                    {
                        "id": row["canonicalId"],
                        "fingerprint": row["fingerprint"],
                    }
                    for row in entry["definitionRows"]
                ],
                "definitionFingerprint": entry["definitionFingerprint"],
                "retiredRows": entry["stale"],
                # ⛔ 528 / Q5: the ids alone were a list nothing could be compared against. The
                # reason travels with them so a row that goes dark a SECOND way — an absent anchor
                # whose file then leaves the tree — is a difference `--check` refuses to bless.
                "retirements": {row: entry["retirements"][row]["reason"] for row in entry["stale"]},
                **entry["run"],
            }
            for entry in data
        ],
    }


def recorded_retirements() -> dict[str, str]:
    """`"<table> <row>" -> reason`, exactly as the report on disk records it.

    ⚑ 528. Deliberately tolerant of a bullet with no reason, and that is not a shim kept for its own
    sake: the first regeneration after this field existed read a report written before it, and it
    had to read every bullet there as ALREADY RECORDED rather than as a retirement happening now.
    Everything before the first separator is the id; a bullet with no separator answers "".
    """

    if not REPORT.exists():
        return {}
    out: dict[str, str] = {}
    for line in REPORT.read_text().splitlines():
        if not line.startswith("- ") or not re.match(r"- \d+ ", line):
            continue
        identity, separator, rest = line[2:].strip().partition(RETIREMENT_SEPARATOR)
        out[identity.strip()] = rest.split(RETIREMENT_SEPARATOR)[0].strip() if separator else ""
    return out


def recorded_stale() -> set[str]:
    return set(recorded_retirements())


def parse_retire_flags(argv: list[str]) -> tuple[list[str], str | None]:
    """Collect every `--retire "<table> <row>:<reason>"` value, in the order they were given."""

    values: list[str] = []
    index = 0
    while index < len(argv):
        token = argv[index]
        if token == RETIRE_FLAG:
            if index + 1 >= len(argv):
                return values, f'{RETIRE_FLAG} needs a "<table> <row>:<reason>" value'
            values.append(argv[index + 1])
            index += 2
            continue
        if token.startswith(f"{RETIRE_FLAG}="):
            values.append(token.split("=", 1)[1])
            index += 1
            continue
        index += 1
    return values, None


def match_retirement_names(values: list[str], newly: dict[str, dict]) -> tuple[set[str], list[str]]:
    """Accept only a name that QUOTES the measurement, and say what is wrong with one that does not.

    ⛔ 528. The acknowledgement has to cost a read. A flag that took a bare row id could be pasted
    forward from a previous run, or typed off the refusal's first line without opening anything;
    requiring the measured reason back means the caller has at least read what the census found.
    ⚠️ It is NOT evidence that the caller looked at the code — nothing here can be. It is the
    cheapest barrier that a copy-forward cannot pass, and the refusal says the rest in words.
    """

    named: set[str] = set()
    problems: list[str] = []
    for value in values:
        identity, separator, reason = value.rpartition(":")
        identity, reason = identity.strip(), reason.strip()
        if not separator or not identity:
            problems.append(f'{value!r} is not "<table> <row>:<reason>"')
            continue
        if identity not in newly:
            problems.append(
                f"{identity} did not go retired in this census, so there is nothing to name"
            )
            continue
        unknown = [word for word in reason.split("+") if word not in RETIREMENT_REASONS]
        if unknown:
            problems.append(
                f"{identity} is named {', '.join(unknown)}, which is not a reason this census can "
                f"measure — it measures {', '.join(RETIREMENT_REASONS)}"
            )
            continue
        measured = newly[identity]["reason"]
        if reason != measured:
            problems.append(f"{identity} is {measured} here, and the name says {reason or '(none)'}")
            continue
        named.add(identity)
    return named, problems


def _first_line(label: str, width: int = 116) -> str:
    line = " ".join(label.split())
    return line if len(line) <= width else f"{line[: width - 1]}…"


def retirement_refusal(unnamed: dict[str, dict]) -> list[str]:
    """The whole of what a reader is told when a row goes dark. `425`: a refusal carries its remedy.

    ⚠️ Read the second paragraph before changing any of it. It states that this tool CANNOT tell a
    moved anchor from a deleted subject (Q3), which is why the remedy is two branches a person
    chooses between rather than one the tool picks. ⛔ A sentence here that claimed the difference
    would be the same defect this rail exists to close, wearing the rail's own badge.
    """

    plural = "s" if len(unnamed) != 1 else ""
    lines = [
        f"⛔ {len(unnamed)} mutation row{plural} went retired in this census and "
        f"{'are' if len(unnamed) != 1 else 'is'} not named — "
        f"{'they protect' if len(unnamed) != 1 else 'it protects'} nothing from here on:",
    ]
    for identity, record in sorted(unnamed.items()):
        where = ", ".join(record["paths"])
        lines.append(
            f"   {identity}{RETIREMENT_SEPARATOR}{record['reason']}"
            f"{RETIREMENT_SEPARATOR}{where}"
        )
        lines.append(f"     {_first_line(record['label'])}")
    lines += [
        "",
        "⚠️ This tool cannot tell an anchor whose TEXT MOVED from one whose SUBJECT IS GONE, and it",
        "   will not re-anchor anything for you. A person has to look:",
        "",
        "   1 · Open the path above and find what the row was pointing at.",
        "       · the subject is still there and only the bytes moved — CORRECT the anchor in place,",
        "         re-verify that one row RED by hand, and regenerate again. A corrected anchor keeps",
        "         a verdict it never earned until somebody re-takes it.",
        "       · the subject is gone — the row is genuinely retired and there is nothing to repair.",
        "   2 · Regenerate naming what you saw, one flag per row:",
        "",
    ]
    quoted = " ".join(
        f'{RETIRE_FLAG} "{identity}:{record["reason"]}"'
        for identity, record in sorted(unnamed.items())
    )
    lines += [
        f"       pnpm run mutations:census -- {quoted}",
        "",
        "Nothing was written. CENSUS.md and ATTESTATION.json still describe the tree they described.",
    ]
    return lines


def recorded_attestation() -> dict | None:
    if not ATTESTATION.exists():
        return None
    try:
        value = json.loads(ATTESTATION.read_text())
    except Exception:
        return None
    return value if isinstance(value, dict) else None


def normalized_report(text: str) -> str:
    """Ignore only the necessarily pre-commit provenance stamp; every claim stays deterministic."""

    lines = text.splitlines()
    prefix = "**Generated by `scripts/mutations/census.py` at `"
    for index, line in enumerate(lines):
        if line.startswith(prefix) and line.endswith("`.** Regenerate with"):
            lines[index] = f"{prefix}<tree>`.** Regenerate with"
            break
    return "\n".join(lines) + ("\n" if text.endswith("\n") else "")


def main() -> int:
    if sys.argv[1:2] == ["--begin-active-mutation"]:
        if len(sys.argv) not in {6, 7}:
            print(
                "usage: census.py --begin-active-mutation TABLE ZERO_BASED_INDEX "
                "PRISTINE_ROOT OWNER_PID [PINNED_DEFINITION]",
                file=sys.stderr,
            )
            return 2
        try:
            begin_active_mutation(*sys.argv[2:])
        except (OSError, ValueError) as error:
            print(f"⛔ active mutation epoch refused: {error}", file=sys.stderr)
            return 1
        return 0

    retire_values, retire_usage = parse_retire_flags(sys.argv[1:])
    if retire_usage:
        print(f"⛔ {retire_usage}")
        return 2
    if retire_values and "--check" in sys.argv:
        print(f"⛔ {RETIRE_FLAG} records a retirement, and --check records nothing.")
        print("\nRun the regeneration that writes it, then let the gate read what it wrote.")
        return 2

    if "--check" in sys.argv:
        try:
            configure_active_mutation_view()
        except (OSError, ValueError) as error:
            print(f"⛔ active mutation epoch is invalid: {error}")
            return 1
    elif _active_mutation_path().exists() or _active_mutation_path().is_symlink():
        print("⛔ refusing to regenerate the census while a mutation epoch is active.")
        print("\nRestore the tree and finish or interrupt the owning mutation run first.")
        return 1

    preflight = mutation_preflight_violations()
    if preflight:
        print("⛔ mutation execution preflight failed:")
        for path, rule, detail in preflight:
            print(f"   {path}: [{rule}] {detail}")
        print(
            "\nRepair the runner contract or Bash-3.2 compatibility defect before "
            "regenerating or accepting mutation evidence."
        )
        return 1

    try:
        data = census()
        assert_active_mutation_unchanged()
    except (OSError, ValueError) as error:
        if _ACTIVE_MUTATION is None:
            raise
        print(f"⛔ active mutation changed while the census was reading it: {error}")
        return 1
    live_stale = {f"{e['table']} {row}" for e in data for row in e["stale"]}
    live_attestation = attestation(data)
    if "--check" in sys.argv:
        unchanged = sorted(
            f"{entry['table']} {row}" for entry in data for row in entry["unchanged"]
        )
        if unchanged:
            print("⛔ mutation rows contain identical old/new edits:")
            for row in unchanged:
                print(f"   {row}")
            print(
                "\nRepair each identical edit so every declared edit changes its target before "
                "recording a verdict."
            )
            return 1
        recorded = recorded_attestation()
        if recorded is None:
            print("⛔ mutation ATTESTATION.json is missing or unreadable.")
            print("\nRegenerate with `pnpm run mutations:census`.")
            return 1
        new = sorted(live_stale - recorded_stale())
        healed = sorted(recorded_stale() - live_stale)
        if new:
            print("⛔ mutation rows went stale since CENSUS.md — they now protect nothing:")
            for row in new:
                print(f"   {row}")
            print("\nEither restore the anchor (and re-run that row), or regenerate the census with")
            print("`pnpm run mutations:census` to retire it deliberately.")
            return 1
        if healed:
            print("⚠️ rows recorded as retired now apply again; regenerate CENSUS.md:")
            for row in healed:
                print(f"   {row}")
            return 1
        if recorded != live_attestation:
            old_tables = {
                entry.get("table"): entry
                for entry in recorded.get("tables", [])
                if isinstance(entry, dict) and isinstance(entry.get("table"), str)
            }
            changed = []
            for entry in live_attestation["tables"]:
                if old_tables.get(entry["table"]) != entry:
                    changed.append(entry["table"])
            changed.extend(sorted(set(old_tables) - {e["table"] for e in data}))
            print("⛔ mutation definitions or run attestations changed since ATTESTATION.json:")
            print(f"   tables: {', '.join(dict.fromkeys(changed)) or '(summary only)'}")
            print(
                "\nRegenerate with `pnpm run mutations:census` only when the definition or "
                "artefact change is deliberate. An unrun row may never be called recorded."
            )
            return 1
        if not REPORT.exists() or normalized_report(REPORT.read_text()) != render(data, "<tree>"):
            print("⛔ mutation CENSUS.md does not match the generated machine attestation.")
            print("\nRegenerate with `pnpm run mutations:census`; CI validates the human claims too.")
            return 1
        try:
            assert_active_mutation_unchanged()
        except (OSError, ValueError) as error:
            print(f"⛔ active mutation changed before the census check completed: {error}")
            return 1
        total = sum(e["rows"] for e in data)
        states = live_attestation["summary"]["rowsByRunState"]
        print(
            f"mutation census ok — {total} defined rows across {len(data)} tables; "
            f"{states['complete']} complete, {states['partial-or-invalid']} partial-or-invalid, "
            f"{states['unrun']} unrun; {len(live_stale)} retired, each recorded with the reason "
            "it stopped matching. Definitions, full canonical ids, run artefacts and controls "
            "match the machine attestation; no row was re-run."
        )
        return 0

    # ⛔ 528 · THE REGENERATION IS THE LOUD SURFACE, because it is the only one present when a row
    # goes dark. `--check`'s `new` rail compares against CENSUS.md and the documented order of work
    # is regenerate-then-gate, so by the time the gate looks, this write has already moved the
    # reference. Nothing below re-anchors, repairs or guesses: it refuses, names, and hands the
    # decision to a person.
    recorded = recorded_retirements()
    live_retirements = {
        f"{entry['table']} {row}": entry["retirements"][row]
        for entry in data
        for row in entry["stale"]
    }
    newly_retired = {
        identity: record
        for identity, record in live_retirements.items()
        if identity not in recorded
    }
    named, naming_problems = match_retirement_names(retire_values, newly_retired)
    if naming_problems:
        print(f"⛔ {RETIRE_FLAG} was given something this census cannot confirm:")
        for problem in naming_problems:
            print(f"   {problem}")
        print(
            f"\nEvery {RETIRE_FLAG} names one row that went retired in THIS run and quotes the "
            "reason\nmeasured for it. Nothing was written."
        )
        return 1
    unnamed = {
        identity: record for identity, record in newly_retired.items() if identity not in named
    }
    if unnamed:
        for line in retirement_refusal(unnamed):
            print(line)
        return 1

    # ⚑ The other direction, reported and NOT refused. A row that starts applying again is a row
    # whose recorded verdict was measured against text it no longer matches — the same unearned
    # verdict a hand correction leaves — but HO-050 §3 ruled on retirement, so this says so and
    # writes. `--check` still refuses a heal it was not regenerated for.
    healed = sorted(set(recorded) - set(live_retirements))
    if healed:
        print(f"⚑ {len(healed)} row(s) recorded as retired are not retired in this census:")
        for identity in healed:
            was = recorded[identity] or "(no reason recorded)"
            print(f"   {identity} · was {was}")
        print(
            "   ⚠️ Applying again is not the same as being re-verified. Whatever verdict each one\n"
            "      carries was measured against text it no longer matches."
        )

    REPORT.write_text(render(data, head()))
    ATTESTATION.write_text(json.dumps(live_attestation, indent=2, ensure_ascii=False) + "\n")
    total = sum(e["rows"] for e in data)
    states = live_attestation["summary"]["rowsByRunState"]
    retired_note = f"{len(live_stale)} retired"
    if named:
        retired_note += f" ({len(named)} newly retired and named)"
    print(
        f"{REPORT} + {ATTESTATION} · {total} defined rows · {states['complete']} complete · "
        f"{states['partial-or-invalid']} partial-or-invalid · {states['unrun']} unrun · "
        f"{retired_note}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
