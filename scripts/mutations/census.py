def row_fingerprint(table: str, row) -> str:
    """Fingerprint the proposition a row actually tests, including ordered replacements."""

    payload = {
        "table": table,
        "id": row_id(str(row[0])),
        "label": str(row[0]),
        "edits": [list(edit) for edit in edits_of(row)],
    }
    encoded = json.dumps(
        payload, ensure_ascii=False, separators=(",", ":"), sort_keys=True
    ).encode()
    return hashlib.sha256(encoded).hexdigest()


