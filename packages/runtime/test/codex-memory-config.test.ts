import {
  chmodSync,
  existsSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { afterEach, beforeEach, describe, expect, it } from 'vitest'
import { parse as parseToml } from 'smol-toml'
import {
  CODEX_MEMORY_PROVENANCE,
  CODEX_MEMORY_SETTINGS,
  ensureCodexMemoryConfig,
  mergeCodexMemoryConfig,
} from '../src/codex/memory-config'
import { removeStaleCodexPermissionConfig } from '../src/codex/stale-permission-config'

/**
 * 🔴 **314 · the two gates, merged into a file Codex also writes.**
 *
 * ## What 312 measured, and what these tests hold the merge to
 *
 * The configuration that put the four dedicated memory calls into a real child's inventory was
 * `[features] memories = true` **plus** `[memories] dedicated_tools = true`; the feature alone
 * injected the summary and exposed no tools at all. Those two, and the two switches 312 corrected
 * (`use_memories` is the whole surface; `generate_memories` is extraction eligibility and does NOT
 * hide `add_ad_hoc_note`), are what {@link CODEX_MEMORY_SETTINGS} names.
 *
 * ⛔ **And 312 measured what happens to the FILE.** Appending a second `[features]` table is a hard
 * `-32600` *"duplicate key"* — not last-one-wins — and rewriting the file whole deleted an unrelated
 * `apps = true` and Codex's own `[projects."…"] trust_level`, of which Codex re-added only the
 * current cwd's. So the byte-for-byte survival assertions below are the finding, not decoration.
 *
 * ## ⚠️ What this file cannot reach
 *
 * ⛔ **It cannot prove a tool exists.** Codex's TOML parser silently accepts keys that cannot exist —
 * 312 measured `[memories] not_a_real_field = true` accepted with no error — so a test that reads
 * the file back proves the file, never the child. The oracle for the four `memories__*` names is a
 * real child's inventory, and it lives in `packages/runtime/smoke/codex-memory-config.smoke.ts`.
 */

/** A second, deliberately independent reader — so a bug in the module's scanner cannot hide here. */
function keysWritten(text: string): string[] {
  const found: string[] = []
  let table = ''
  for (const line of text.split('\n')) {
    const header = /^\[([A-Za-z0-9_-]+)\]\s*$/.exec(line.trim())
    if (header) {
      table = header[1]!
      continue
    }
    const assign = /^([A-Za-z0-9_-]+)\s*=/.exec(line)
    if (assign && table !== '') found.push(`${table}.${assign[1]!}`)
  }
  return found
}

const CODEX_OWN = `model = "gpt-5.6-luna"

[features]
apps = true

[projects."/Users/someone/dev/thing"]
trust_level = "trusted"
`

describe('the two gates, merged in place (314 §1)', () => {
  describe('the merge itself, on text', () => {
    it('⛔ a home with no config at all gets one, and it is 312’s exact positive', () => {
      const merge = mergeCodexMemoryConfig(null)
      expect(merge.kind).toBe('merged')
      if (merge.kind !== 'merged') return
      const parsed = parseToml(merge.text) as Record<string, Record<string, unknown>>
      expect(parsed['features']).toEqual({ memories: true })
      expect(parsed['memories']).toEqual({
        dedicated_tools: true,
        use_memories: true,
        generate_memories: true,
      })
    })

    it('⛔ …and it does NOT begin `# Generated by BroBot2`', () => {
      // 🔴 **The single most load-bearing negative in this file.** `stale-permission-config.ts`
      // deletes exactly the file that starts with those bytes. Marking a file Codex co-owns would
      // arm our own sweep against Codex's trust entries — on every launch, forever.
      const merge = mergeCodexMemoryConfig(null)
      if (merge.kind !== 'merged') throw new Error('expected a merge')
      expect(merge.text.startsWith('# Generated by BroBot2')).toBe(false)
      expect(merge.text).toContain(CODEX_MEMORY_PROVENANCE)
    })

    it('🔴 merges INTO the existing [features] table — apps and the trust entry survive verbatim', () => {
      const merge = mergeCodexMemoryConfig(CODEX_OWN)
      if (merge.kind !== 'merged') throw new Error(`expected a merge, got ${merge.kind}`)
      expect(merge.text).toContain('apps = true')
      expect(merge.text).toContain('[projects."/Users/someone/dev/thing"]\ntrust_level = "trusted"')
      expect(merge.text).toContain('model = "gpt-5.6-luna"')
      const parsed = parseToml(merge.text) as Record<string, Record<string, unknown>>
      expect(parsed['features']).toEqual({ apps: true, memories: true })
    })

    it('🔴 …and NEVER appends a second [features] table — 312’s `-32600` duplicate key', () => {
      const merge = mergeCodexMemoryConfig(CODEX_OWN)
      if (merge.kind !== 'merged') throw new Error('expected a merge')
      expect(merge.text.split('\n').filter((line) => line.trim() === '[features]')).toHaveLength(1)
      // …and the parser agrees, which is the thing the app-server would have refused over.
      expect(() => parseToml(merge.text)).not.toThrow()
    })

    it('⚠️ a key that is already there is CORRECTED in place, not duplicated', () => {
      const merge = mergeCodexMemoryConfig(
        '[features]\nmemories = false\n\n[memories]\ndedicated_tools = true\nuse_memories = false\ngenerate_memories = true\n',
      )
      if (merge.kind !== 'merged') throw new Error('expected a merge')
      expect(merge.text.split('\n').filter((line) => /^memories = /.test(line))).toHaveLength(1)
      expect(merge.text.split('\n').filter((line) => /^use_memories = /.test(line))).toHaveLength(1)
      const parsed = parseToml(merge.text) as Record<string, Record<string, unknown>>
      expect(parsed['features']!['memories']).toBe(true)
      expect(parsed['memories']!['use_memories']).toBe(true)
    })

    it('⚑ a config that already says all four is UNCHANGED — nothing is opened for writing', () => {
      const settled =
        '[features]\nmemories = true\n\n[memories]\ndedicated_tools = true\nuse_memories = true\ngenerate_memories = true\n'
      expect(mergeCodexMemoryConfig(settled)).toEqual({ kind: 'unchanged' })
    })

    it('⚠️ an EMPTY config.toml is treated as fresh — it gets the provenance block too', () => {
      // Found reviewing this diff: a zero-byte file is not an existing document, and merging into it
      // as though it were left the keys with no note saying who wrote them or that they come back.
      const merge = mergeCodexMemoryConfig('')
      if (merge.kind !== 'merged') throw new Error(`expected a merge, got ${merge.kind}`)
      expect(merge.text).toContain(CODEX_MEMORY_PROVENANCE)
      // …and a file with real content does NOT get it — the block is about a file we created (193).
      const existing = mergeCodexMemoryConfig(CODEX_OWN)
      if (existing.kind !== 'merged') throw new Error('expected a merge')
      expect(existing.text).not.toContain(CODEX_MEMORY_PROVENANCE)
    })

    it('⛔ an unparseable config is REFUSED — never rewritten from a guess', () => {
      const merge = mergeCodexMemoryConfig('[features\nbroken = ')
      expect(merge.kind).toBe('refused')
      if (merge.kind !== 'refused') return
      expect(merge.why).toContain('does not parse')
    })

    it('⛔ a `features` that is not a table is refused rather than replaced', () => {
      // Somebody's value, and TOML would reject the result anyway. The point is that this app does
      // not decide that a scalar at a name it wants is available for reuse.
      const merge = mergeCodexMemoryConfig('features = 3\n')
      expect(merge.kind).toBe('refused')
      if (merge.kind !== 'refused') return
      expect(merge.why).toContain('[features] is not a table')
    })

    it('🔴 the verification catches the scanner’s own blind spot — `[features]` inside a string', () => {
      // ⛔ **The reason the merge is checked by a real parser before it is published.** A line
      // scanner cannot tell a table header from the same three words inside a multi-line string, so
      // it edits the string. Nothing here claims the scanner is right; this asserts that a scanner
      // that is WRONG cannot publish.
      const trap = 'note = """\n[features]\nmemories = false\n"""\n'
      const merge = mergeCodexMemoryConfig(trap)
      expect(merge.kind).toBe('refused')
      // …and the control: the reader really would have been fooled — that string contains exactly
      // what the scanner looks for, so this is a blind spot and not a hypothetical one.
      expect(keysWritten(trap)).toEqual(['features.memories'])
    })

    it('🔴 …and the PRESERVATION half catches what the "did it set them" half cannot', () => {
      // ⛔ **The one construction where only rule (3) can say no.** Every one of our four keys is
      // already correct in the real `[memories]` table, and the string above them happens to contain
      // `use_memories = false` — which the scanner matches FIRST and rewrites. The merge therefore
      // lands all four values correctly and silently edits somebody's prose. Nothing but the
      // leaf-by-leaf comparison against the original document notices.
      const trap = [
        '[memories]',
        'note = """',
        'use_memories = false',
        '"""',
        'dedicated_tools = true',
        'use_memories = true',
        'generate_memories = true',
        '',
      ].join('\n')
      const merge = mergeCodexMemoryConfig(trap)
      expect(merge.kind).toBe('refused')
      if (merge.kind !== 'refused') return
      expect(merge.why).toContain('memories.note')
    })

    it('⚠️ a CRLF config stays CRLF', () => {
      const merge = mergeCodexMemoryConfig('[features]\r\napps = true\r\n')
      if (merge.kind !== 'merged') throw new Error('expected a merge')
      expect(merge.text).not.toMatch(/[^\r]\n/)
      expect(
        (parseToml(merge.text) as Record<string, Record<string, unknown>>)['features'],
      ).toEqual({ apps: true, memories: true })
    })

    it('⚠️ a config with no trailing newline gets one, and still parses', () => {
      const merge = mergeCodexMemoryConfig('[features]\napps = true')
      if (merge.kind !== 'merged') throw new Error('expected a merge')
      expect(merge.text.endsWith('\n')).toBe(true)
      expect(() => parseToml(merge.text)).not.toThrow()
    })

    it('⚑ every key the merge writes carries a comment saying why, for the person who opens it', () => {
      const merge = mergeCodexMemoryConfig(null)
      if (merge.kind !== 'merged') throw new Error('expected a merge')
      for (const setting of CODEX_MEMORY_SETTINGS) {
        expect(merge.text).toContain(`# ${setting.key}: ${setting.why}`)
      }
    })

    it('🔴 …and the keys written are EXACTLY the ones the table declares, both directions', () => {
      // The binding the desktop disclosure rests on: `provider-config.ts` renders its sentence from
      // this same table, so a key added to the writer and not to the table (or the reverse) is a
      // sentence that lies. Read back with an independent scanner.
      const merge = mergeCodexMemoryConfig(null)
      if (merge.kind !== 'merged') throw new Error('expected a merge')
      expect(keysWritten(merge.text).sort()).toEqual(
        CODEX_MEMORY_SETTINGS.map((one) => `${one.table}.${one.key}`).sort(),
      )
      // …and the reader can say more than four, so the equality above is a measurement (193).
      expect(keysWritten('[features]\nmemories = true\nsomething_else = 1\n')).toEqual([
        'features.memories',
        'features.something_else',
      ])
    })
  })

  describe('putting it on disk', () => {
    let home: string

    beforeEach(() => {
      home = mkdtempSync(join(tmpdir(), 'brobot2-314-memory-'))
    })

    afterEach(() => {
      rmSync(home, { recursive: true, force: true })
    })

    const config = (): string => join(home, 'config.toml')

    it('⛔ writes the file when the home has none — the ordinary case today', () => {
      expect(ensureCodexMemoryConfig(home)).toEqual({ outcome: 'written', path: config() })
      const parsed = parseToml(readFileSync(config(), 'utf8')) as Record<
        string,
        Record<string, unknown>
      >
      expect(parsed['features']!['memories']).toBe(true)
      expect(parsed['memories']!['dedicated_tools']).toBe(true)
    })

    it('🔒 …and 160’s stale sweep leaves what we wrote strictly alone', () => {
      // ⛔ **The interaction §1 demands is checked, not reasoned about.** That sweep runs on every
      // launch, immediately before this write, and it deletes a `config.toml` beginning with our own
      // generated header. A home we have touched must not be silently wiped by our own migration.
      ensureCodexMemoryConfig(home)
      const written = readFileSync(config(), 'utf8')
      expect(removeStaleCodexPermissionConfig(home)).toBe(null)
      expect(readFileSync(config(), 'utf8')).toBe(written)
    })

    it('⚑ is idempotent — a second call writes nothing and does not touch the file', () => {
      ensureCodexMemoryConfig(home)
      const before = statSync(config())
      expect(ensureCodexMemoryConfig(home)).toEqual({ outcome: 'unchanged', path: config() })
      const after = statSync(config())
      expect(after.ino).toBe(before.ino)
      expect(after.mtimeMs).toBe(before.mtimeMs)
    })

    it('🔴 preserves Codex’s own entries byte-for-byte', () => {
      writeFileSync(config(), CODEX_OWN)
      expect(ensureCodexMemoryConfig(home).outcome).toBe('written')
      const after = readFileSync(config(), 'utf8')
      expect(after).toContain('[projects."/Users/someone/dev/thing"]\ntrust_level = "trusted"')
      expect(after).toContain('apps = true')
    })

    it('⚠️ keeps the file’s own mode — this file is Codex’s as much as ours', () => {
      writeFileSync(config(), CODEX_OWN)
      chmodSync(config(), 0o644)
      ensureCodexMemoryConfig(home)
      expect(statSync(config()).mode & 0o777).toBe(0o644)
    })

    it('⛔ leaves an unparseable config exactly as it was, and says why', () => {
      const broken = '[features\nbroken = '
      writeFileSync(config(), broken)
      const result = ensureCodexMemoryConfig(home)
      expect(result.outcome).toBe('refused')
      expect(readFileSync(config(), 'utf8')).toBe(broken)
    })

    it('⛔ …and never leaves a staging file behind, on any outcome', () => {
      writeFileSync(config(), '[features\nbroken = ')
      ensureCodexMemoryConfig(home)
      ensureCodexMemoryConfig(join(home, 'nope')) // a home that is not there
      writeFileSync(config(), CODEX_OWN)
      ensureCodexMemoryConfig(home)
      expect(readdirSync(home).filter((name) => name.includes('.brobot-'))).toEqual([])
    })

    it('🔴 a config that changed under us is NOT clobbered — the write is abandoned', () => {
      // ⛔ **The window this closes is Codex appending a trust entry while we are staging.** There
      // is no lock — Codex takes none either — so the guarantee is: publish over the bytes we read,
      // or do not publish. The seam is the only way to be inside a window measured in syscalls.
      writeFileSync(config(), CODEX_OWN)
      const appended = `${CODEX_OWN}\n[projects."/Users/someone/dev/other"]\ntrust_level = "trusted"\n`
      const result = ensureCodexMemoryConfig(home, {
        beforePublish: () => writeFileSync(config(), appended),
      })
      expect(result.outcome).toBe('raced')
      expect(readFileSync(config(), 'utf8')).toBe(appended)
      expect(readdirSync(home).filter((name) => name.includes('.brobot-'))).toEqual([])
      // …and the next launch simply does it, which is what makes abandoning safe.
      expect(ensureCodexMemoryConfig(home).outcome).toBe('written')
      expect(readFileSync(config(), 'utf8')).toContain('/Users/someone/dev/other')
    })

    it('⛔ an UNREADABLE config is refused, never overwritten with a fresh one', () => {
      // ⚠️ **Unreadable is not absent, and collapsing the two would be 312's whole-file rewrite
      // arrived at by an error path.** A permission wall, a broken mount, a file being replaced —
      // none of them is "this home has no config", and the one thing that must not follow from not
      // being able to read Codex's entries is deleting them.
      writeFileSync(config(), CODEX_OWN)
      chmodSync(config(), 0o000)
      try {
        const result = ensureCodexMemoryConfig(home)
        expect(result.outcome).toBe('refused')
        expect(result.why).toContain('not readable')
      } finally {
        chmodSync(config(), 0o600)
      }
      expect(readFileSync(config(), 'utf8')).toBe(CODEX_OWN)
    })

    it('⚠️ a home that does not exist is a `failed`, not a throw — a launch must not die over memory', () => {
      const result = ensureCodexMemoryConfig(join(home, 'not-there'))
      expect(result.outcome).toBe('failed')
      expect(existsSync(join(home, 'not-there'))).toBe(false)
    })
  })
})
