import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { afterEach, beforeEach, describe, expect, it } from 'vitest'
import { removeStaleCodexPermissionConfig } from '../src/codex/stale-permission-config'

/**
 * 🔴 **160 §2 · what 157 left in the provider homes, and what happens to it now.**
 *
 * 157 wrote a `[permissions.*]` block into every session's own `CODEX_HOME` before each launch and
 * selected it by id. 160 sends the legacy `sandbox` strings again and names no profile, so the block
 * is selected by nothing. **One home on the live install already had one.**
 *
 * ## ⚑ Measured on the pinned 0.146.0 binary before any of this was written
 *
 * A disposable `CODEX_HOME` carrying 157's exact file, launched the way 160 launches:
 *
 * | request | result |
 * |---|---|
 * | `thread/start` `sandbox: 'read-only'` | ok — `{type:'readOnly'}`, `activePermissionProfile: **null**` |
 * | `thread/start` `sandbox: 'danger-full-access'` | ok — `{type:'dangerFullAccess'}`, profile `null` |
 * | cold-process `thread/resume` on a real rollout | ok — `dangerFullAccess`, profile `null` |
 * | stderr / `configWarning` | **empty** |
 *
 * ⛔ **So the answer to "nothing, a warning, or a failure" is NOTHING** — which is why the tests
 * below assert that a home carrying the block still LAUNCHES, and why the removal is hygiene rather
 * than a fix.
 *
 * ⚠️ **Inert is not ignored.** Naming the block explicitly on a `command/exec` in the same process
 * proved it live: a read of a denied root came back *"Operation not permitted"* and `ps` came back
 * *"sandbox-exec: execvp() of 'ps' failed"*. A loaded, credential-denying policy that nothing selects
 * is the 142 §5 defect in file form — its own first line claims it is rewritten every launch, and
 * nothing rewrites it.
 */

const STALE_157_CONFIG = `# Generated by BroBot2 — rewritten on every session launch. Do not edit.
#
# Two named permission profiles, one per approval mode.

default_permissions = "brobot-ask"

[permissions."brobot-ask"]
description = "BroBot · ask — read-only, every action escalates to a prompt"
extends = ":read-only"

[permissions."brobot-auto"]
description = "BroBot · auto — the whole machine, minus the roots that hold credentials"
extends = ":workspace"

[permissions."brobot-auto".filesystem]
"/" = "write"
"/Users/someone/.claude" = "deny"
"/Users/someone/.codex" = "deny"

[permissions."brobot-auto".network]
enabled = true
`

describe('157’s stale `[permissions.*]` block (160 §2)', () => {
  let home: string

  beforeEach(() => {
    home = mkdtempSync(join(tmpdir(), 'brobot2-stale-config-'))
  })

  afterEach(() => {
    rmSync(home, { recursive: true, force: true })
  })

  describe('the removal itself', () => {
    it('⛔ deletes a config this app generated', () => {
      const path = join(home, 'config.toml')
      writeFileSync(path, STALE_157_CONFIG)
      expect(removeStaleCodexPermissionConfig(home)).toBe(path)
      expect(existsSync(path)).toBe(false)
    })

    it('🔒 …and leaves a config it did NOT generate strictly alone', () => {
      // ⚠️ **The fail-safe, and the only reason this is safe to run on every launch.** "Delete a
      // config file from a Codex home" is exactly the operation that must not be approximate. A
      // header match is the whole test of ownership: `provisionProviderHome` has never written a
      // `config.toml` and nothing else in this app writes one, so anything without the marker is
      // somebody else's and is not ours to remove.
      const path = join(home, 'config.toml')
      const theirs = '[permissions."mine"]\nextends = ":workspace"\n'
      writeFileSync(path, theirs)
      expect(removeStaleCodexPermissionConfig(home)).toBe(null)
      expect(readFileSync(path, 'utf8')).toBe(theirs)
    })

    it('🔒 …and the header must be at the START, not merely somewhere in the file', () => {
      // ⚠️ **M19 found this missing, and it is the difference between a marker and a mention.** A
      // hand-written config that cites this app — a comment saying where its sibling came from, a
      // pasted block, a note — contains the marker without having been generated by it. Under a
      // substring test that file is deleted; under `startsWith` it is a config somebody wrote, and
      // this app does not delete those.
      const path = join(home, 'config.toml')
      const theirs = `model = "gpt-5"\n# see also: ${'# Generated by BroBot2'} — the app's own home\n`
      writeFileSync(path, theirs)
      expect(removeStaleCodexPermissionConfig(home)).toBe(null)
      expect(readFileSync(path, 'utf8')).toBe(theirs)
    })

    it('a home with no config at all is the ordinary case, and is not a failure', () => {
      // After the first launch on this build every home is in this state, forever. It must be quiet.
      expect(removeStaleCodexPermissionConfig(home)).toBe(null)
    })

    it('…and neither is a home that is not there', () => {
      expect(removeStaleCodexPermissionConfig(join(home, 'nope'))).toBe(null)
    })
  })
})
