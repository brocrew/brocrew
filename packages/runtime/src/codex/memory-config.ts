import { closeSync, readFileSync, renameSync, statSync, unlinkSync, writeSync } from 'node:fs'
import { join } from 'node:path'
import { parse as parseToml } from 'smol-toml'
import { aStagingName, createFreshFile } from '../internal/provider-home'

/**
 * 🔴 **Turn Codex memory on, in a file Codex also writes** (314, on 312's measurement).
 *
 * ## ⛔ Two gates, and the second is the one nobody would have guessed
 *
 * `[features] memories = true` **alone** injects the memory summary and starts the background
 * extraction pipeline — and exposes **no tools at all**. 312 proved that negative separately: the
 * feature-only arm genuinely had memory on (the seeded summary reached the model) and still carried
 * no tool declarations. `dedicated_tools` defaults **false**, and it is the difference between a
 * profile that has a memory and one that can read or write it.
 *
 * The other two are not the read/write pair the name suggests:
 *
 * | key | what 312 measured it doing |
 * |---|---|
 * | `use_memories` | the **whole surface** — `false` removes summary injection AND all four tools, even with `dedicated_tools = true` |
 * | `generate_memories` | whether a NEW thread is eligible for background extraction (`memory_mode` in `state_5.sqlite`). ⚠️ `false` does **not** hide `add_ad_hoc_note` — it is not a write prohibition |
 *
 * ⛔ **Both default true once the feature is on, and both are written anyway.** 165's rule, one
 * field over: an omitted field is not "no opinion" — see the repository's standing note that an
 * absent SDK/TOML field can be a value with its own meaning. A person reading this file by hand
 * must be able to see what this profile's answer is, and a provider default that moves must not
 * move this profile with it.
 *
 * ## 🔴 The constraint that decides the implementation
 *
 * Codex writes to this same file, and 312 measured that the two obvious approaches both fail:
 *
 * | what was done to `config.toml` | what happened |
 * |---|---|
 * | append a **second** `[features]` table | 🔴 hard failure — RPC `-32600` *"duplicate key"*, stderr *"Invalid configuration; using defaults."* **Not last-one-wins.** |
 * | **rewrite** the file with just what we want | ⛔ deleted an unrelated `apps = true` **and** Codex's own `[projects."…"] trust_level`. Codex re-added only the CURRENT cwd's trust on the next launch; the rest were gone for good |
 * | **edit the existing table in place** | ✅ parsed; `apps = true` and the trust entry survived byte-for-byte |
 *
 * ⚑ **So the only measurable safe operation is an in-place merge into the one existing table.**
 * That is what {@link mergeCodexMemoryConfig} does, and it is a LINE edit rather than a
 * parse-and-re-serialize: a TOML writer would reorder tables, drop comments and normalize spellings,
 * which is the "rewrite" row of that table wearing a library.
 *
 * ## 🔒 A hand-rolled edit that a real parser has to agree with before it is published
 *
 * ⛔ **A line scanner cannot be right about TOML, and this one does not claim to be.** `[features]`
 * inside a multi-line string looks exactly like a table header; a dotted `features.memories` at the
 * root is the same key under another spelling; an array of tables ends a body the same way a table
 * does. So the scanner is allowed to be approximate and the RESULT is checked: the merged text is
 * re-parsed, and it is published only when a real parser agrees that
 *
 *  1. it parses at all,
 *  2. all four settings resolve to the intended values, **and**
 *  3. every other leaf in the document is still present and equal — and no new leaf appeared.
 *
 * Anything else refuses and leaves the file exactly as it was. ⚠️ That is not a belt-and-braces
 * flourish: (3) is the assertion that turns *"we edited one line"* into *"Codex's trust entries are
 * still here"*, which is the whole finding.
 *
 * ## ⚠️ What is deliberately NOT here
 *
 * ⛔ **No `# Generated by BroBot2` header.** `stale-permission-config.ts` deletes exactly the file
 * that begins with those bytes, so marking a file Codex co-owns would arm our own sweep against
 * Codex's trust entries. The provenance comment below is written for a person, and
 * {@link removeStaleCodexPermissionConfig} is asked in a test what it makes of it.
 *
 * ⛔ **No lock.** `withProviderHomeLock` would exclude our own second process and could not exclude
 * Codex, which takes no lock and appends trust entries whenever it likes — so the lock would buy an
 * exclusion we do not get while adding a ten-second fail-closed throw to every launch, which is the
 * trade `home-boot.ts` argues against in its own terms. What is here instead is narrower and
 * honest: the publish is atomic (staged file + `rename`), the file's bytes are re-read and compared
 * immediately before the `rename`, and a mismatch abandons the write rather than clobbering it.
 * ⚠️ **The residual window is those two syscalls**, and it is only ever open on a launch that has
 * something to change — which for any given home is the FIRST one, because the merge is idempotent
 * and every launch after it returns `unchanged` without opening anything for writing.
 *
 * ⚠️ **It never throws.** A home whose config cannot be merged still launches: the cost is that
 * memory is off, which is where every home was before this existed, and refusing to start Codex
 * over it would be a far larger failure than the one being fixed.
 *
 * ⚠️ **It overwrites a hand-edited value.** A person who sets `use_memories = false` in this file
 * gets it set back on the next launch — that is what *"every provider home gets the gates, on every
 * launch"* means, and it is why {@link CODEX_MEMORY_PROVENANCE} says so in the file itself rather
 * than leaving somebody to discover it.
 */

/** The file, in the profile's own `CODEX_HOME`. Same name `stale-permission-config.ts` uses. */
const CODEX_CONFIG_FILENAME = 'config.toml'

/**
 * One key BroBot writes, and the reason it is written rather than left to a default.
 *
 * ⚑ **This table is the single source.** The file's comments are rendered from it, the merge reads
 * it, and the desktop's provider-config disclosure derives its sentence from it — so the sentence a
 * user reads cannot drift from the keys the app writes. 306's shape: state the rule once.
 */
export interface CodexMemorySetting {
  /** The TOML table the key lives in. */
  readonly table: string
  /** The key inside it. */
  readonly key: string
  /** What we write. All four are `true`; the type keeps that visible rather than implied. */
  readonly value: boolean
  /** One line, for the person who opens this file by hand. */
  readonly why: string
}

