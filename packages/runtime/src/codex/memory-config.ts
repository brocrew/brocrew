/**
 * The provenance block, written once at the top of a `config.toml` this app had to create.
 *
 * ⛔ **It does not begin `# Generated by BroBot2`** — see the module note. It says who wrote the
 * four keys, that everything else in the file belongs to Codex and to the user, and that these four
 * come back on the next launch.
 */
export const CODEX_MEMORY_PROVENANCE = [
  "# BroCrew keeps this profile's Codex memory switched on.",
  '#',
  "# It merges ONLY the four keys below into this file and never rewrites it, so Codex's own",
  '# entries — project trust, model providers, anything you add — survive untouched. Those four',
  '# are re-applied every time BroCrew opens this profile, so an edit to them here is replaced on',
  '# the next launch; everything else in this file is yours.',
].join('\n')

/** The comment BroBot puts above a key it is adding, so the file explains itself. */
function noteFor(setting: CodexMemorySetting): string {
  return `# ${setting.key}: ${setting.why}`
}

/** The result of merging our settings into a config's text. */
export type CodexMemoryMerge =
  /** The text to publish. Different from the input by construction. */
  | { readonly kind: 'merged'; readonly text: string }
  /** All four already resolve to what we would write. Nothing is opened for writing. */
  | { readonly kind: 'unchanged' }
  /** We could not produce a merge a parser agrees with. The file must be left exactly as it is. */
  | { readonly kind: 'refused'; readonly why: string }

/** A bare, `"quoted"` or `'literal'` single key, decoded — or `null` when it is neither. */
function decodeKey(token: string): string | null {
  if (/^[A-Za-z0-9_-]+$/.test(token)) return token
  // ⚠️ A basic string with an ESCAPE is refused rather than half-decoded. `"\u006d…"` is a legal
  // spelling of one of our keys and this scanner has no business guessing at it; the parse-based
  // value check above the scanner is what notices, and the verification below is what refuses.
  const basic = /^"([^"\\]*)"$/.exec(token)
  if (basic) return basic[1]!
  const literal = /^'([^']*)'$/.exec(token)
  if (literal) return literal[1]!
  return null
}

/** The table a `[header]` line declares, or `null` for anything else (including `[[arrays]]`). */
function tableHeader(line: string): string | null {
  const match = /^\s*\[\s*([^[\]]+?)\s*\]\s*(?:#.*)?$/.exec(line)
  return match ? decodeKey(match[1]!) : null
}

/** Does this line start a new table of any shape? Used only to END a body. */
function startsTable(line: string): boolean {
  return line.trimStart().startsWith('[')
}

/** The key a `key = …` line assigns, or `null` (blank, comment, dotted key, continuation). */
function assignedKey(line: string): string | null {
  const match = /^\s*([A-Za-z0-9_-]+|"[^"\\]*"|'[^']*')\s*=/.exec(line)
  return match ? decodeKey(match[1]!) : null
}

/** Where a table's header sits and where its body ends (exclusive). */
interface TableSpan {
  readonly header: number
  readonly bodyEnd: number
}

function findTable(lines: readonly string[], name: string): TableSpan | null {
  for (let index = 0; index < lines.length; index++) {
    if (tableHeader(lines[index]!) !== name) continue
    let end = index + 1
    while (end < lines.length && !startsTable(lines[end]!)) end++
    return { header: index, bodyEnd: end }
  }
  return null
}

/**
 * The line a new key goes on: after the table's last real assignment, before its trailing blank
 * lines and before any comment block that is plainly introducing the NEXT table.
 */
function insertionPoint(lines: readonly string[], span: TableSpan): number {
  let at = span.bodyEnd
  while (at > span.header + 1) {
    const line = lines[at - 1]!.trim()
    if (line !== '' && !line.startsWith('#')) break
    at--
  }
  return at
}

/** Every leaf in a parsed document, as `dotted.path` → a comparable rendering of its value. */
function leaves(
  node: unknown,
  path: string[] = [],
  into = new Map<string, string>(),
): Map<string, string> {
  if (Array.isArray(node)) {
    node.forEach((item, index) => leaves(item, [...path, String(index)], into))
    return into
  }
  if (isPlainObject(node)) {
    for (const [key, value] of Object.entries(node)) leaves(value, [...path, key], into)
    return into
  }
  into.set(path.join('.'), render(node))
  return into
}

/** A plain TOML table — deliberately NOT `Date`, which is an object smol-toml really returns. */
function isPlainObject(node: unknown): node is Record<string, unknown> {
  return (
    typeof node === 'object' && node !== null && !Array.isArray(node) && !(node instanceof Date)
  )
}

/** A value as a string that compares the way TOML means it to — `bigint` and dates included. */
function render(value: unknown): string {
  if (typeof value === 'bigint') return `bigint:${value.toString()}`
  if (value instanceof Date) return `date:${value.toISOString()}`
  return `${typeof value}:${String(value)}`
}

/** What the document says about one setting today, or `undefined` when it says nothing. */
function currentValue(parsed: unknown, setting: CodexMemorySetting): unknown {
  if (!isPlainObject(parsed)) return undefined
  const table = parsed[setting.table]
  if (!isPlainObject(table)) return undefined
  return table[setting.key]
}

/** The dotted paths our settings own — the only leaves a merge is allowed to change. */
const OURS = new Set(CODEX_MEMORY_SETTINGS.map((one) => `${one.table}.${one.key}`))

/**
 * 🔴 **The merge, and the only place the four keys are put into text.**
 *
 * Pure on purpose: the whole algorithm is exercised on strings, so the filesystem tests are about
 * publishing and the merge tests are about TOML.
 */
export function mergeCodexMemoryConfig(existing: string | null): CodexMemoryMerge {
  // ⚠️ **A zero-byte `config.toml` is as fresh as no file at all**, and treating it as an existing
  // document would merge the keys in without the provenance block that says who wrote them and that
  // they come back on every launch. Found reviewing this diff — there was nothing to preserve.
  const original = existing ?? ''
  const fresh = original.trim() === ''

  let before: unknown
  try {
    before = parseToml(original)
  } catch (error) {
    // ⛔ We cannot merge into a document we cannot read, and guessing at its structure is how the
    // "rewrite" row of 312's table happens by accident. The launch attestation
    // (`assertCodexSqliteHomeContained`) is what reports an unparseable config to the user.
    return { kind: 'refused', why: `the existing config.toml does not parse: ${errorText(error)}` }
  }

  // ⚠️ A `features` or `memories` that is not a table at all (`features = 3`) cannot be merged into
  // and must not be replaced — that value is somebody's, and TOML would reject the result anyway.
  for (const setting of CODEX_MEMORY_SETTINGS) {
    const table = isPlainObject(before) ? before[setting.table] : undefined
    if (table !== undefined && !isPlainObject(table)) {
      return { kind: 'refused', why: `[${setting.table}] is not a table in this config.toml` }
    }
  }

  const wrong = CODEX_MEMORY_SETTINGS.filter(
    (setting) => currentValue(before, setting) !== setting.value,
  )
  if (wrong.length === 0) return { kind: 'unchanged' }

  const eol = original.includes('\r\n') ? '\r\n' : '\n'
  const lines = original.length === 0 ? [] : original.split(/\r?\n/)
  if (fresh) lines.push(...CODEX_MEMORY_PROVENANCE.split('\n'), '')

  // Grouped by table so a missing table is appended once, with every key it is missing.
  for (const table of [...new Set(CODEX_MEMORY_SETTINGS.map((one) => one.table))]) {
    const settings = CODEX_MEMORY_SETTINGS.filter((one) => one.table === table)
    const span = findTable(lines, table)
    if (span === null) {
      // ⚠️ Appended at the END of the file, which is the only position that cannot change what an
      // existing table's body contains. A leading blank line keeps it off the previous table's tail.
      if (lines.length > 0 && lines[lines.length - 1]!.trim() !== '') lines.push('')
      lines.push(`[${table}]`)
      for (const setting of settings)
        lines.push(noteFor(setting), `${setting.key} = ${setting.value}`)
      continue
    }
    // ⛔ **A key that is already there is REPLACED in place; one that is missing is added once, in
    // table order, at a single point.** Replacements do not change the line count, so the insertion
    // point computed from this span stays valid — and collecting the additions into ONE splice is
    // what keeps them in the order this table declares them. Three separate splices at the same
    // index would emit them backwards, which is a file a person reads.
    const additions: string[] = []
    for (const setting of settings) {
      let found = -1
      for (let index = span.header + 1; index < span.bodyEnd; index++) {
        if (assignedKey(lines[index]!) === setting.key) {
          found = index
          break
        }
      }
      if (found >= 0) {
        const indent = /^\s*/.exec(lines[found]!)![0]
        lines[found] = `${indent}${setting.key} = ${setting.value}`
      } else {
        additions.push(noteFor(setting), `${setting.key} = ${setting.value}`)
      }
    }
    if (additions.length > 0) lines.splice(insertionPoint(lines, span), 0, ...additions)
  }

  const text = lines.join(eol) + (lines.length > 0 && lines[lines.length - 1] !== '' ? eol : '')
  return verify(original, before, text)
}

/**
 * 🔒 **The scanner's output, held to a real parser before anybody sees it** (see the module note).
 *
 * Three questions, and the third is the finding: does every other leaf still say exactly what it
 * said, and did nothing new appear?
 */
function verify(original: string, before: unknown, text: string): CodexMemoryMerge {
  let after: unknown
  try {
    after = parseToml(text)
  } catch (error) {
    return { kind: 'refused', why: `the merged config.toml would not parse: ${errorText(error)}` }
  }
  for (const setting of CODEX_MEMORY_SETTINGS) {
    if (currentValue(after, setting) !== setting.value) {
      return {
        kind: 'refused',
        why: `the merge did not set ${setting.table}.${setting.key}`,
      }
    }
  }
  const was = leaves(before)
  const now = leaves(after)
  for (const [path, value] of was) {
    if (OURS.has(path)) continue
    if (now.get(path) !== value) {
      return { kind: 'refused', why: `the merge would have changed or dropped ${path}` }
    }
  }
  for (const path of now.keys()) {
    if (OURS.has(path) || was.has(path)) continue
    return { kind: 'refused', why: `the merge would have added ${path}` }
  }
  // ⚠️ A merge that produced the input byte-for-byte is not a merge; publishing it would churn the
  // file's mtime and its inode for nothing. Unreachable while `wrong` is non-empty, and asserted
  // rather than assumed — the same rule the mutation harness applies to a row whose replacement
  // equals its anchor.
  return text === original ? { kind: 'unchanged' } : { kind: 'merged', text }
}

function errorText(error: unknown): string {
  return error instanceof Error ? error.message : String(error)
}

/** What one call did. Never a throw — see the module note. */
export type CodexMemoryConfigOutcome =
  /** The merged file is on disk. */
  | 'written'
  /** The four keys already said what we would write. */
  | 'unchanged'
  /** We declined to edit this file, and it is untouched. */
  | 'refused'
  /** The file changed under us between the read and the publish; the next launch will retry. */
  | 'raced'
  /** The write itself failed (a full disk, a read-only home). The file is untouched. */
  | 'failed'

export interface CodexMemoryConfigResult {
  readonly outcome: CodexMemoryConfigOutcome
  readonly path: string
  /** Present for every outcome except `written` and `unchanged`. */
  readonly why?: string
}

/** Test seam: a hook fired between the staged write and the re-read that guards the rename. */
export interface CodexMemoryConfigSeams {
  readonly beforePublish?: () => void
}

/**
 * 🔴 **Make this provider home's Codex memory keys say what BroBot means them to say.**
 *
 * Apply this on provisioning and every launch, like `removeStaleCodexPermissionConfig`. Homes are created lazily with no migration hook, so existing profiles must also receive these memory settings.
 */
export function ensureCodexMemoryConfig(
  providerHome: string,
  seams: CodexMemoryConfigSeams = {},
): CodexMemoryConfigResult {
  const path = join(providerHome, CODEX_CONFIG_FILENAME)
  let existing: string | null
  try {
    existing = readFileSync(path, 'utf8')
  } catch (error) {
    if (!isAbsent(error)) {
      // ⚠️ Unreadable is NOT absent. Writing a fresh file over something we could not read would be
      // the whole-file rewrite 312 measured, chosen by an error path.
      return { outcome: 'refused', path, why: `config.toml is not readable: ${errorText(error)}` }
    }
    existing = null
  }

  const merge = mergeCodexMemoryConfig(existing)
  if (merge.kind === 'unchanged') return { outcome: 'unchanged', path }
  if (merge.kind === 'refused') return { outcome: 'refused', path, why: merge.why }
  return publish(path, merge.text, existing, seams)
}

/**
 * ⛔ **Never written at the published name** — the shape `workspace.ts` and `provider-home.ts` both
 * use. A staged file created `O_CREAT|O_EXCL` cannot be redirected by anything planted at that name,
 * and `rename` replaces the leaf in one step, so a crash cannot leave a truncated `config.toml`
 * behind — which would be a config that fails to parse, which is a profile that cannot launch.
 */
function publish(
  path: string,
  text: string,
  expected: string | null,
  seams: CodexMemoryConfigSeams,
): CodexMemoryConfigResult {
  // Keep the file's own mode when it has one: this file is Codex's as much as ours.
  let mode = 0o600
  try {
    mode = statSync(path).mode & 0o777
  } catch {
    // absent — 0600 under a 0700 home is the right default for a file we are creating
  }
  const staged = aStagingName(path)
  let fd: number
  try {
    fd = createFreshFile(staged, mode)
  } catch (error) {
    return { outcome: 'failed', path, why: `could not stage the merge: ${errorText(error)}` }
  }
  const discard = (outcome: 'raced' | 'failed', why: string): CodexMemoryConfigResult => {
    try {
      unlinkSync(staged)
    } catch {
      // best effort — one staging file beside the config is better than losing the reason
    }
    return { outcome, path, why }
  }
  try {
    writeSync(fd, text)
  } catch (error) {
    return discard('failed', `could not write the merge: ${errorText(error)}`)
  } finally {
    try {
      closeSync(fd)
    } catch {
      // the bytes are written; a failed close is not a failed publish
    }
  }
  seams.beforePublish?.()
  // ⛔ **The last look before the rename** (see the module note on why there is no lock). Codex
  // appends its own trust entries to this file whenever it likes, and renaming our merge over an
  // appended entry would delete exactly the thing 312 measured us not deleting. Two syscalls apart
  // is not zero, and the docblock says so rather than claiming exclusion we do not have.
  let now: string | null
  try {
    now = readFileSync(path, 'utf8')
  } catch (error) {
    if (!isAbsent(error)) {
      return discard('failed', `config.toml stopped being readable: ${errorText(error)}`)
    }
    now = null
  }
  if (now !== expected) {
    return discard(
      'raced',
      'config.toml changed between the read and the write; the next launch will retry',
    )
  }
  try {
    renameSync(staged, path)
  } catch (error) {
    return discard('failed', `could not publish the merge: ${errorText(error)}`)
  }
  return { outcome: 'written', path }
}

function isAbsent(error: unknown): boolean {
  return (error as NodeJS.ErrnoException | undefined)?.code === 'ENOENT'
}
