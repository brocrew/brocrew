import { readFileSync, rmSync } from 'node:fs'
import { join } from 'node:path'

/**
 * Remove a `config.toml` that an earlier build generated with a `[permissions.*]` block and that no
 * launch selects any more. The block is inert (thread start and resume ignore it and Codex warns
 * about nothing) but still parsed and enforceable, so leaving it would present a deny-list that is
 * not in force.
 *
 * Only a file that begins with {@link GENERATED_HEADER} is deleted; any other `config.toml`, and an
 * unreadable one, is left alone. It runs on every launch because homes are provisioned lazily with
 * no migration hook, and costs one small read that almost always finds no file.
 */

/** The first line of every file this app generated; nothing else here writes a `config.toml`. */
const GENERATED_HEADER = '# Generated by BroBot2'

/** The file in each session's own `CODEX_HOME`. */
const CODEX_CONFIG_FILENAME = 'config.toml'

/**
 * Delete a generated `config.toml` from this provider home. Returns the path removed, or `null` when
 * there was nothing of ours, which is the ordinary case.
 */
export function removeStaleCodexPermissionConfig(providerHome: string): string | null {
  const path = join(providerHome, CODEX_CONFIG_FILENAME)
  let text: string
  try {
    text = readFileSync(path, 'utf8')
  } catch {
    return null // no home, no file, or not readable — all "nothing of ours here"
  }
  if (!text.startsWith(GENERATED_HEADER)) return null // somebody else's config; not ours to delete
  rmSync(path, { force: true })
  return path
}
