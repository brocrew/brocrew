import { readFileSync, rmSync } from 'node:fs'
import { join } from 'node:path'

/**
 * Remove the `config.toml` **157 wrote and 160 stopped selecting** — the one migration this revert
 * needs.
 *
 * ## What 157 left behind
 *
 * 157 wrote a `[permissions.*]` block into every session's own `CODEX_HOME` before each launch, and
 * selected it by id on `thread/start` / `thread/resume` / `turn/start`. 160 sends the legacy
 * `sandbox` strings again and names no profile, so the block on disk is selected by nothing. One
 * home on the live install already had it.
 *
 * ## 🔴 What a stale block actually does to a launch — measured, not reasoned
 *
 * Against the pinned 0.146.0 binary, a disposable `CODEX_HOME` carrying 157's exact file, launched
 * the way 160 launches:
 *
 * | request | result |
 * |---|---|
 * | `thread/start` `sandbox: 'read-only'` | ok — `{type:'readOnly'}`, `activePermissionProfile: **null**` |
 * | `thread/start` `sandbox: 'danger-full-access'` | ok — `{type:'dangerFullAccess'}`, profile `null` |
 * | cold-process `thread/resume` on a real rollout | ok — `dangerFullAccess`, profile `null` |
 * | stderr / `configWarning` across all of the above | **empty** |
 *
 * ⚑ **So the answer to "nothing, a warning, or a failure" is NOTHING.** The block is inert.
 *
 * ⚠️ **Inert is not the same as ignored, and the difference is why this file exists.** The block is
 * still parsed and still enforceable — naming it explicitly on a `command/exec` in the same process
 * proved it live: reading a denied root came back *"Operation not permitted"* and `ps` came back
 * *"sandbox-exec: execvp() of 'ps' failed"*. What sits in those homes is a working, loaded,
 * credential-denying policy that nothing selects.
 *
 * ⛔ **Which makes leaving it the 142 §5 defect in file form.** Its own first line says *"rewritten
 * on every session launch"* and nothing rewrites it; its body is a deny-list over `~/.claude`,
 * `~/.codex` and `userData` that is not in force. The next person to open that home — or to ask
 * whether Codex is denied the credential roots — would read a policy and take it for a measurement.
 * A file stating a false machine fact is worse than no file, for the same reason a comment is.
 *
 * ## 🔒 It deletes only a file it can prove is ours
 *
 * The header line below is the fail-safe. `provisionProviderHome` has never written a `config.toml`,
 * nothing else in this app writes one, and the user's own `~/.codex` is never reached from here —
 * but "delete a config file from a Codex home" is exactly the operation that must not be approximate.
 * A `config.toml` this app did not generate is left strictly alone, and so is an unreadable one.
 *
 * ⚠️ **On every launch, not once**, for the reason 157's write ran on every launch: there is no
 * migration hook, homes are provisioned lazily, and a home last opened by the 157 build can turn up
 * at any later date. It costs one small read that almost always ENOENTs.
 */

/** The first line of every file 157 generated. Nothing else in this app writes a `config.toml`. */
const GENERATED_HEADER = '# Generated by BroBot2'

/** The file 157 wrote into each session's own `CODEX_HOME`. */
const CODEX_CONFIG_FILENAME = 'config.toml'

/**
 * Delete a 157-generated `config.toml` from this provider home. Returns the path removed, or `null`
 * when there was nothing of ours to remove — which is the ordinary case and not a failure.
 */
export function removeStaleCodexPermissionConfig(providerHome: string): string | null {
  const path = join(providerHome, CODEX_CONFIG_FILENAME)
  let text: string
  try {
    text = readFileSync(path, 'utf8')
  } catch {
    return null // no home, no file, or not readable — all "nothing of ours here"
  }
  if (!text.startsWith(GENERATED_HEADER)) return null // somebody else's config; not ours to delete
  rmSync(path, { force: true })
  return path
}
